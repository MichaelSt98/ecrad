MODULE SW_REPLAY_BENCH_MOD
  USE PARKIND1, ONLY : JPIM,JPRB,JPIB,JPRD
  USE YOMHOOK, ONLY : LHOOK,DR_HOOK,JPHOOK
  USE RADIATION_IO, ONLY : NULOUT
  USE RADIATION_CONFIG, ONLY : CONFIG_TYPE
  USE SW_REPLAY_IO_MOD, ONLY : SW_REPLAY_BLOCK_TYPE
  USE RADIATION_MCICA_SW_BATCH_MOD, ONLY : SW_BATCH_WORKSPACE_TYPE,SOLVE_SW_BATCH
  USE RADIATION_MCICA_SW_BATCH_REFERENCE, ONLY : SOLVER_MCICA_ACC_GPOINT_SW_IMPL
  USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY : IEEE_IS_FINITE
  IMPLICIT NONE
  PRIVATE
  PUBLIC :: MEASURE_SW_REPLAY
  TYPE REPLAY_BUFFER_TYPE
    INTEGER(KIND=JPIM) :: NLEV,NCOL,NG,NBAND,CAPACITY
    INTEGER(KIND=JPIM), ALLOCATABLE :: FIRST(:),LAST(:),SEED(:,:)
    REAL(KIND=JPRB), ALLOCATABLE :: MU(:,:),CLOUD(:,:,:,:),OVERLAP(:,:,:)
    REAL(KIND=JPRB), ALLOCATABLE :: OPT(:,:,:,:,:),COPT(:,:,:,:,:),BOUNDARY(:,:,:,:)
    REAL(KIND=JPRB), ALLOCATABLE :: COVER(:,:),SURFACE(:,:,:,:),FLUX(:,:,:,:)
  END TYPE REPLAY_BUFFER_TYPE
#include "abor1.intfb.h"
CONTAINS
SUBROUTINE INIT_BUFFER(YDB,YDSOURCE,KCAP)
  TYPE(REPLAY_BUFFER_TYPE), INTENT(OUT) :: YDB
  TYPE(SW_REPLAY_BLOCK_TYPE), INTENT(IN) :: YDSOURCE
  INTEGER(KIND=JPIM), INTENT(IN) :: KCAP
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('INIT_BUFFER',0,ZHOOK_HANDLE)
  YDB%NLEV=YDSOURCE%NLEV
  YDB%NCOL=YDSOURCE%NCOL
  YDB%NG=YDSOURCE%NG
  YDB%NBAND=YDSOURCE%NBAND
  YDB%CAPACITY=KCAP
  ALLOCATE(YDB%FIRST(KCAP),YDB%LAST(KCAP),YDB%SEED(YDB%NCOL,KCAP),YDB%MU(YDB%NCOL,KCAP))
  ALLOCATE(YDB%CLOUD(YDB%NCOL,YDB%NLEV,KCAP,2),YDB%OVERLAP(YDB%NCOL,YDB%NLEV-1,KCAP))
  ALLOCATE(YDB%OPT(YDB%NG,YDB%NLEV,YDB%NCOL,KCAP,3))
  ALLOCATE(YDB%COPT(YDB%NBAND,YDB%NLEV,YDB%NCOL,KCAP,3),YDB%BOUNDARY(YDB%NG,YDB%NCOL,KCAP,3))
  ALLOCATE(YDB%COVER(YDB%NCOL,KCAP),YDB%SURFACE(YDB%NG,YDB%NCOL,KCAP,4))
  ALLOCATE(YDB%FLUX(YDB%NCOL,YDB%NLEV+1,KCAP,6))
  ! Capacity beyond the last active batch has defined data and output sentinels.
  YDB%FIRST(:)=1
  YDB%LAST(:)=0
  YDB%SEED(:,:)=0
  YDB%MU(:,:)=0.0_JPRB
  YDB%CLOUD(:,:,:,:)=0.0_JPRB
  YDB%OVERLAP(:,:,:)=0.0_JPRB
  YDB%OPT(:,:,:,:,:)=0.0_JPRB
  YDB%COPT(:,:,:,:,:)=0.0_JPRB
  YDB%BOUNDARY(:,:,:,:)=0.0_JPRB
  YDB%COVER(:,:)=-9876.0_JPRB
  YDB%SURFACE(:,:,:,:)=-9876.0_JPRB
  YDB%FLUX(:,:,:,:)=-9876.0_JPRB
  !$ACC ENTER DATA COPYIN(YDB)
  !$ACC ENTER DATA COPYIN(YDB%FIRST,YDB%LAST,YDB%SEED,YDB%MU,YDB%CLOUD,YDB%OVERLAP)
  !$ACC ENTER DATA COPYIN(YDB%OPT,YDB%COPT,YDB%BOUNDARY,YDB%COVER,YDB%SURFACE,YDB%FLUX)
  IF (LHOOK) CALL DR_HOOK('INIT_BUFFER',1,ZHOOK_HANDLE)
END SUBROUTINE INIT_BUFFER

SUBROUTINE RELEASE_BUFFER(YDB)
  TYPE(REPLAY_BUFFER_TYPE), INTENT(INOUT) :: YDB
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('RELEASE_BUFFER',0,ZHOOK_HANDLE)
  !$ACC WAIT(1)
  !$ACC EXIT DATA DELETE(YDB%FIRST,YDB%LAST,YDB%SEED,YDB%MU,YDB%CLOUD,YDB%OVERLAP)
  !$ACC EXIT DATA DELETE(YDB%OPT,YDB%COPT,YDB%BOUNDARY,YDB%COVER,YDB%SURFACE,YDB%FLUX)
  !$ACC EXIT DATA DELETE(YDB)
  DEALLOCATE(YDB%FIRST,YDB%LAST,YDB%SEED,YDB%MU,YDB%CLOUD,YDB%OVERLAP)
  DEALLOCATE(YDB%OPT,YDB%COPT,YDB%BOUNDARY,YDB%COVER,YDB%SURFACE,YDB%FLUX)
  IF (LHOOK) CALL DR_HOOK('RELEASE_BUFFER',1,ZHOOK_HANDLE)
END SUBROUTINE RELEASE_BUFFER

SUBROUTINE PACK_BUFFER(YDB,YDDOMAIN,KSTART,KACTIVE)
  TYPE(REPLAY_BUFFER_TYPE), INTENT(INOUT) :: YDB
  TYPE(SW_REPLAY_BLOCK_TYPE), INTENT(IN) :: YDDOMAIN(:)
  INTEGER(KIND=JPIM), INTENT(IN) :: KSTART,KACTIVE
  INTEGER(KIND=JPIM) :: JB,ISOURCE,JF
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('PACK_BUFFER',0,ZHOOK_HANDLE)
  DO JB=1,KACTIVE
    ISOURCE=KSTART+JB-1
    YDB%FIRST(JB)=YDDOMAIN(ISOURCE)%FIRST
    YDB%LAST(JB)=YDDOMAIN(ISOURCE)%LAST
    YDB%SEED(:,JB)=YDDOMAIN(ISOURCE)%SEED(:)
    YDB%MU(:,JB)=YDDOMAIN(ISOURCE)%MU(:)
    YDB%OVERLAP(:,:,JB)=YDDOMAIN(ISOURCE)%OVERLAP(:,:)
    DO JF=1,2
      YDB%CLOUD(:,:,JB,JF)=YDDOMAIN(ISOURCE)%CLOUD(:,:,JF)
    ENDDO
    DO JF=1,3
      YDB%OPT(:,:,:,JB,JF)=YDDOMAIN(ISOURCE)%OPT(:,:,:,JF)
      YDB%COPT(:,:,:,JB,JF)=YDDOMAIN(ISOURCE)%COPT(:,:,:,JF)
      YDB%BOUNDARY(:,:,JB,JF)=YDDOMAIN(ISOURCE)%BOUNDARY(:,:,JF)
    ENDDO
  ENDDO
  IF (LHOOK) CALL DR_HOOK('PACK_BUFFER',1,ZHOOK_HANDLE)
END SUBROUTINE PACK_BUFFER

SUBROUTINE UPLOAD_BUFFER(YDB)
  TYPE(REPLAY_BUFFER_TYPE), INTENT(IN) :: YDB
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('UPLOAD_BUFFER',0,ZHOOK_HANDLE)
  ! Upload the full allocated capacity, including the partial final batch.
  !$ACC UPDATE DEVICE(YDB%FIRST,YDB%LAST,YDB%SEED,YDB%MU,YDB%CLOUD,YDB%OVERLAP) ASYNC(1)
  !$ACC UPDATE DEVICE(YDB%OPT,YDB%COPT,YDB%BOUNDARY) ASYNC(1)
  !$ACC WAIT(1)
  IF (LHOOK) CALL DR_HOOK('UPLOAD_BUFFER',1,ZHOOK_HANDLE)
END SUBROUTINE UPLOAD_BUFFER

SUBROUTINE DOWNLOAD_BUFFER(YDB)
  TYPE(REPLAY_BUFFER_TYPE), INTENT(INOUT) :: YDB
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('DOWNLOAD_BUFFER',0,ZHOOK_HANDLE)
  !$ACC UPDATE SELF(YDB%COVER,YDB%SURFACE,YDB%FLUX) ASYNC(1)
  !$ACC WAIT(1)
  IF (LHOOK) CALL DR_HOOK('DOWNLOAD_BUFFER',1,ZHOOK_HANDLE)
END SUBROUTINE DOWNLOAD_BUFFER

SUBROUTINE RUN_SOLVER(YDB,YDWORK,YDCONFIG,KACTIVE,KMODE)
  TYPE(REPLAY_BUFFER_TYPE), INTENT(INOUT) :: YDB
  TYPE(SW_BATCH_WORKSPACE_TYPE), INTENT(INOUT) :: YDWORK
  TYPE(CONFIG_TYPE), INTENT(IN) :: YDCONFIG
  INTEGER(KIND=JPIM), INTENT(IN) :: KACTIVE,KMODE
  INTEGER(KIND=JPIM) :: JB,IFIRST,ILAST
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('RUN_SOLVER',0,ZHOOK_HANDLE)
  IF (KMODE == 0) THEN
    DO JB=1,KACTIVE
      IFIRST=YDB%FIRST(JB)
      ILAST=YDB%LAST(JB)
      CALL SOLVER_MCICA_ACC_GPOINT_SW_IMPL(YDB%NLEV,YDB%NCOL,IFIRST,ILAST,YDB%NG, &
        & YDCONFIG%PDF_SAMPLER%NCDF,YDCONFIG%PDF_SAMPLER%NFSD,YDB%NBAND,YDCONFIG%USE_BETA_OVERLAP,.FALSE., &
        & YDCONFIG%CLOUD_FRACTION_THRESHOLD,YDCONFIG%CLOUD_INHOM_DECORR_SCALING, &
        & YDCONFIG%PDF_SAMPLER%FSD1,YDCONFIG%PDF_SAMPLER%INV_FSD_INTERVAL, &
        & YDCONFIG%I_BAND_FROM_REORDERED_G_SW,YDCONFIG%PDF_SAMPLER%VAL,YDB%SEED(:,JB),YDB%MU(:,JB), &
        & YDB%CLOUD(:,:,JB,1),YDB%CLOUD(:,:,JB,2),YDB%OVERLAP(:,:,JB), &
        & YDB%OPT(:,:,IFIRST:ILAST,JB,1),YDB%OPT(:,:,IFIRST:ILAST,JB,2),YDB%OPT(:,:,IFIRST:ILAST,JB,3), &
        & YDB%COPT(:,:,IFIRST:ILAST,JB,1),YDB%COPT(:,:,IFIRST:ILAST,JB,2),YDB%COPT(:,:,IFIRST:ILAST,JB,3), &
        & YDB%BOUNDARY(:,IFIRST:ILAST,JB,1),YDB%BOUNDARY(:,IFIRST:ILAST,JB,2), &
        & YDB%BOUNDARY(:,IFIRST:ILAST,JB,3),YDB%COVER(:,JB), &
        & YDB%SURFACE(:,:,JB,1),YDB%SURFACE(:,:,JB,2),YDB%SURFACE(:,:,JB,3),YDB%SURFACE(:,:,JB,4), &
        & YDB%FLUX(:,:,JB,1),YDB%FLUX(:,:,JB,2),YDB%FLUX(:,:,JB,3),YDB%FLUX(:,:,JB,4), &
        & SW_DN_DIRECT=YDB%FLUX(:,:,JB,5),SW_DN_DIRECT_CLEAR=YDB%FLUX(:,:,JB,6))
    ENDDO
  ELSE
    CALL SOLVE_SW_BATCH(YDWORK,YDCONFIG,KACTIVE,YDB%FIRST,YDB%LAST,YDB%SEED,YDB%MU, &
      & YDB%CLOUD(:,:,:,1),YDB%CLOUD(:,:,:,2),YDB%OVERLAP,YDB%OPT(:,:,:,:,1), &
      & YDB%OPT(:,:,:,:,2),YDB%OPT(:,:,:,:,3),YDB%COPT(:,:,:,:,1),YDB%COPT(:,:,:,:,2),YDB%COPT(:,:,:,:,3), &
      & YDB%BOUNDARY(:,:,:,1),YDB%BOUNDARY(:,:,:,2),YDB%BOUNDARY(:,:,:,3),YDB%COVER,YDB%SURFACE,YDB%FLUX)
  ENDIF
  !$ACC WAIT(1)
  IF (LHOOK) CALL DR_HOOK('RUN_SOLVER',1,ZHOOK_HANDLE)
END SUBROUTINE RUN_SOLVER

SUBROUTINE SCATTER_BUFFER(YDB,KSTART,KACTIVE,PCOVER,PSURFACE,PFLUX)
  TYPE(REPLAY_BUFFER_TYPE), INTENT(IN) :: YDB
  INTEGER(KIND=JPIM), INTENT(IN) :: KSTART,KACTIVE
  REAL(KIND=JPRB), INTENT(INOUT) :: PCOVER(:,:),PSURFACE(:,:,:,:),PFLUX(:,:,:,:)
  INTEGER(KIND=JPIM) :: JB,JF,IDEST
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('SCATTER_BUFFER',0,ZHOOK_HANDLE)
  DO JB=1,KACTIVE
    IDEST=KSTART+JB-1
    PCOVER(:,IDEST)=YDB%COVER(:,JB)
    DO JF=1,4
      PSURFACE(:,:,IDEST,JF)=YDB%SURFACE(:,:,JB,JF)
    ENDDO
    DO JF=1,6
      PFLUX(:,:,IDEST,JF)=YDB%FLUX(:,:,JB,JF)
    ENDDO
  ENDDO
  IF (LHOOK) CALL DR_HOOK('SCATTER_BUFFER',1,ZHOOK_HANDLE)
END SUBROUTINE SCATTER_BUFFER

SUBROUTINE MEASURE_SW_REPLAY(YDDOMAIN,YDCONFIG,KMODE,KCAP,KBOUNDARY,KREPEAT)
  TYPE(SW_REPLAY_BLOCK_TYPE), INTENT(IN) :: YDDOMAIN(:)
  TYPE(CONFIG_TYPE), INTENT(IN) :: YDCONFIG
  INTEGER(KIND=JPIM), INTENT(IN) :: KMODE,KCAP,KBOUNDARY,KREPEAT
  TYPE(REPLAY_BUFFER_TYPE) :: YLB
  TYPE(SW_BATCH_WORKSPACE_TYPE) :: YLWORK
  INTEGER(KIND=JPIM) :: JITER,ISTART,IACTIVE,JB,JF,IBLOCKS
  INTEGER(KIND=JPIB) :: IT0,IT1,IRATE,ITSETUP0,ITSETUP1
  REAL(KIND=JPRB), ALLOCATABLE :: ZCOVER(:,:),ZSURFACE(:,:,:,:),ZFLUX(:,:,:,:)
  REAL(KIND=JPRD) :: ZTIME,ZERROR,ZCHECKSUM
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('MEASURE_SW_REPLAY',0,ZHOOK_HANDLE)
  IBLOCKS=SIZE(YDDOMAIN)
  IF (KMODE == 0 .AND. KCAP /= 1) CALL ABOR1('MEASURE_SW_REPLAY: reference uses K=1')
  IF (KCAP < 1 .OR. KREPEAT < 1) CALL ABOR1('MEASURE_SW_REPLAY: invalid capacity/repetitions')
  CALL SYSTEM_CLOCK(ITSETUP0,IRATE)
  CALL INIT_BUFFER(YLB,YDDOMAIN(1),KCAP)
  IF (KMODE /= 0) CALL YLWORK%INIT(YLB%NLEV,YLB%NCOL,KCAP,YLB%NG,1)
  ALLOCATE(ZCOVER(YLB%NCOL,IBLOCKS),ZSURFACE(YLB%NG,YLB%NCOL,IBLOCKS,4))
  ALLOCATE(ZFLUX(YLB%NCOL,YLB%NLEV+1,IBLOCKS,6))
  !$ACC ENTER DATA COPYIN(YDCONFIG)
  !$ACC ENTER DATA COPYIN(YDCONFIG%I_BAND_FROM_REORDERED_G_SW,YDCONFIG%PDF_SAMPLER%VAL)
  CALL SYSTEM_CLOCK(ITSETUP1)
  WRITE(NULOUT,'(A,ES24.16)') 'SETUP_SECONDS ',DBLE(ITSETUP1-ITSETUP0)/DBLE(IRATE)
  DO JITER=1,KREPEAT
    ZTIME=0.0D0
    DO ISTART=1,IBLOCKS,KCAP
      IACTIVE=MIN(KCAP,IBLOCKS-ISTART+1)
      IF (KBOUNDARY == 1) CALL SYSTEM_CLOCK(IT0)
      CALL PACK_BUFFER(YLB,YDDOMAIN,ISTART,IACTIVE)
      CALL UPLOAD_BUFFER(YLB)
      IF (KBOUNDARY == 0) CALL SYSTEM_CLOCK(IT0)
      CALL RUN_SOLVER(YLB,YLWORK,YDCONFIG,IACTIVE,KMODE)
      IF (KBOUNDARY == 0) THEN
        CALL SYSTEM_CLOCK(IT1)
        ZTIME=ZTIME+DBLE(IT1-IT0)/DBLE(IRATE)
      ENDIF
      CALL DOWNLOAD_BUFFER(YLB)
      CALL SCATTER_BUFFER(YLB,ISTART,IACTIVE,ZCOVER,ZSURFACE,ZFLUX)
      IF (KBOUNDARY == 1) THEN
        CALL SYSTEM_CLOCK(IT1)
        ZTIME=ZTIME+DBLE(IT1-IT0)/DBLE(IRATE)
      ENDIF
    ENDDO
    ! Validation and checksums are outside both measurement boundaries.
    IF (.NOT. ALL(IEEE_IS_FINITE(ZCOVER)) .OR. .NOT. ALL(IEEE_IS_FINITE(ZSURFACE)) &
      & .OR. .NOT. ALL(IEEE_IS_FINITE(ZFLUX))) CALL ABOR1('MEASURE_SW_REPLAY: nonfinite output')
    ZERROR=0.0D0
    DO JB=1,IBLOCKS
      IF (ANY(ZCOVER(:,JB) /= YDDOMAIN(JB)%COVER)) CALL ABOR1('MEASURE_SW_REPLAY: cloud cover differs')
      DO JF=1,4
        ZERROR=MAX(ZERROR,DBLE(MAXVAL(ABS(ZSURFACE(:,:,JB,JF)-YDDOMAIN(JB)%SURFACE(:,:,JF)))))
      ENDDO
      DO JF=1,6
        ZERROR=MAX(ZERROR,DBLE(MAXVAL(ABS(ZFLUX(:,:,JB,JF)-YDDOMAIN(JB)%FLUX(:,:,JF)))))
      ENDDO
      IF (ZERROR > 0.1D0) THEN
        WRITE(NULOUT,*) 'Mismatch at block ',JB,' error ',ZERROR
        CALL ABOR1('MEASURE_SW_REPLAY: SP flux tolerance exceeded')
      ENDIF
    ENDDO
    ZCHECKSUM=SUM(DBLE(ZFLUX))
    WRITE(NULOUT,'(A,5I6,3ES24.16)') 'REPLAY ',KMODE,KCAP,KBOUNDARY,JITER,IBLOCKS,ZTIME,ZERROR,ZCHECKSUM
    FLUSH(NULOUT)
  ENDDO
  !$ACC EXIT DATA DELETE(YDCONFIG%I_BAND_FROM_REORDERED_G_SW,YDCONFIG%PDF_SAMPLER%VAL)
  !$ACC EXIT DATA DELETE(YDCONFIG)
  CALL YLWORK%RELEASE()
  CALL RELEASE_BUFFER(YLB)
  IF (LHOOK) CALL DR_HOOK('MEASURE_SW_REPLAY',1,ZHOOK_HANDLE)
END SUBROUTINE MEASURE_SW_REPLAY
END MODULE SW_REPLAY_BENCH_MOD
