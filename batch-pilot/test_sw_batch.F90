PROGRAM TEST_SW_BATCH
  USE PARKIND1, ONLY : JPIM, JPRB
  USE RADIATION_MCICA_SW_BATCH_MOD, ONLY : SW_BATCH_WORKSPACE_TYPE
  USE RADIATION_IO, ONLY : NULOUT
  IMPLICIT NONE
  TYPE(SW_BATCH_WORKSPACE_TYPE) :: YLWORK1,YLWORK2
  CALL RUN_CASE(YLWORK1,YLWORK2,137,32,1,1,.FALSE.)
  CALL RUN_CASE(YLWORK1,YLWORK2,137,32,3,2,.TRUE.)
  CALL RUN_CASE(YLWORK1,YLWORK2,2,5,4,3,.FALSE.)
  CALL RUN_CASE(YLWORK1,YLWORK2,11,7,3,0,.TRUE.)
  CALL RUN_CASE(YLWORK1,YLWORK2,137,32,3,3,.FALSE.)
  CALL YLWORK1%RELEASE()
  CALL YLWORK2%RELEASE()
  CALL YLWORK1%RELEASE()
  CALL YLWORK2%RELEASE()
  WRITE(NULOUT,'(A,I0)') 'PASS SW batch reference, masks, reuse, resize, queues; real kind=',JPRB
CONTAINS

SUBROUTINE RUN_CASE(YDWORK1,YDWORK2,KLEV,KCOL,KBLOCK,KACTIVE,LDBETA)
  USE RADIATION_CONFIG, ONLY : CONFIG_TYPE
  USE RADIATION_MCICA_SW_BATCH_MOD, ONLY : SOLVE_SW_BATCH
  USE RADIATION_MCICA_SW_BATCH_REFERENCE, ONLY : SOLVER_MCICA_ACC_GPOINT_SW_IMPL
  USE YOMHOOK, ONLY : LHOOK,DR_HOOK,JPHOOK
  USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY : IEEE_IS_FINITE
  TYPE(SW_BATCH_WORKSPACE_TYPE), INTENT(INOUT) :: YDWORK1,YDWORK2
  INTEGER(KIND=JPIM), INTENT(IN) :: KLEV,KCOL,KBLOCK,KACTIVE
  LOGICAL, INTENT(IN) :: LDBETA
  INTEGER(KIND=JPIM), PARAMETER :: IG=112,IBAND=14,INCDF=9,INFSD=4
  REAL(KIND=JPRB), PARAMETER :: ZPOISON=-9876.0_JPRB
  TYPE(CONFIG_TYPE) :: YLCONFIG
  INTEGER(KIND=JPIM) :: IFIRST(KBLOCK),ILAST(KBLOCK),ISEED(KCOL,KBLOCK,2)
  REAL(KIND=JPRB) :: ZMU(KCOL,KBLOCK),ZCLOUD(KCOL,KLEV,KBLOCK),ZFSD(KCOL,KLEV,KBLOCK)
  REAL(KIND=JPRB) :: ZOVER(KCOL,KLEV-1,KBLOCK)
  REAL(KIND=JPRB) :: ZOD(IG,KLEV,KCOL,KBLOCK),ZSSA(IG,KLEV,KCOL,KBLOCK),ZG(IG,KLEV,KCOL,KBLOCK)
  REAL(KIND=JPRB) :: ZODCL(IBAND,KLEV,KCOL,KBLOCK),ZSSACL(IBAND,KLEV,KCOL,KBLOCK)
  REAL(KIND=JPRB) :: ZGCL(IBAND,KLEV,KCOL,KBLOCK)
  REAL(KIND=JPRB) :: ZALBD(IG,KCOL,KBLOCK),ZALBF(IG,KCOL,KBLOCK),ZINCOMING(IG,KCOL,KBLOCK)
  REAL(KIND=JPRB) :: ZCOVER(KCOL,KBLOCK),ZCOVER2(KCOL,KBLOCK),ZREFC(KCOL,KBLOCK,2)
  REAL(KIND=JPRB) :: ZSURF(IG,KCOL,KBLOCK,4),ZSURF2(IG,KCOL,KBLOCK,4),ZREFS(IG,KCOL,KBLOCK,4,2)
  REAL(KIND=JPRB) :: ZFLUX(KCOL,KLEV+1,KBLOCK,6),ZFLUX2(KCOL,KLEV+1,KBLOCK,6)
  REAL(KIND=JPRB) :: ZREFF(KCOL,KLEV+1,KBLOCK,6,2)
  INTEGER(KIND=JPIM) :: JB,JL,JK,JG,IC,IFSD,IREPEAT,IQ
  REAL(KIND=JPRB) :: ZERROR,ZTOL
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
#include "abor1.intfb.h"
  IF (LHOOK) CALL DR_HOOK('TEST_SW_BATCH%RUN_CASE',0,ZHOOK_HANDLE)
  ZTOL=0.001_JPRB
  IF (PRECISION(1.0_JPRB) < 10) ZTOL=0.1_JPRB
  YLCONFIG%N_G_SW=IG
  YLCONFIG%N_BANDS_SW=IBAND
  YLCONFIG%DO_CLEAR=.TRUE.
  YLCONFIG%DO_SW_DELTA_SCALING_WITH_GASES=.FALSE.
  YLCONFIG%USE_BETA_OVERLAP=LDBETA
  YLCONFIG%CLOUD_INHOM_DECORR_SCALING=0.7_JPRB
  YLCONFIG%PDF_SAMPLER%NCDF=INCDF
  YLCONFIG%PDF_SAMPLER%NFSD=INFSD
  YLCONFIG%PDF_SAMPLER%FSD1=0.0_JPRB
  YLCONFIG%PDF_SAMPLER%INV_FSD_INTERVAL=2.0_JPRB
  ALLOCATE(YLCONFIG%I_BAND_FROM_REORDERED_G_SW(IG),YLCONFIG%PDF_SAMPLER%VAL(INCDF,INFSD))
  DO JG=1,IG
    YLCONFIG%I_BAND_FROM_REORDERED_G_SW(JG)=1+MOD(JG-1,IBAND)
  ENDDO
  DO IFSD=1,INFSD
    DO IC=1,INCDF
      YLCONFIG%PDF_SAMPLER%VAL(IC,IFSD)=0.2_JPRB+0.13_JPRB*IC+0.07_JPRB*IFSD
    ENDDO
  ENDDO
  DO JB=1,KBLOCK
    DO JL=1,KCOL
      ZMU(JL,JB)=0.1_JPRB+0.07_JPRB*MOD(JL+JB,12)
      IF (MOD(JL+JB,5) == 0) ZMU(JL,JB)=-0.2_JPRB
      DO JG=1,IG
        ZALBD(JG,JL,JB)=0.05_JPRB+0.001_JPRB*JG
        ZALBF(JG,JL,JB)=0.11_JPRB+0.001_JPRB*JB
        ZINCOMING(JG,JL,JB)=8.0_JPRB+0.01_JPRB*JG
      ENDDO
      DO JK=1,KLEV
        ZFSD(JL,JK,JB)=0.2_JPRB+0.1_JPRB*MOD(JK+JL,13)
        IF (JK < KLEV) ZOVER(JL,JK,JB)=0.1_JPRB*MOD(JK+JL+JB,11)
        DO JG=1,IG
          ZOD(JG,JK,JL,JB)=0.001_JPRB+0.0001_JPRB*MOD(JG+JK+JL,100)
          ZSSA(JG,JK,JL,JB)=0.1_JPRB+0.007_JPRB*MOD(JG+JL,100)
          ZG(JG,JK,JL,JB)=0.5_JPRB
        ENDDO
        DO JG=1,IBAND
          ZODCL(JG,JK,JL,JB)=0.2_JPRB+0.01_JPRB*MOD(JG+JK+JB,20)
          ZSSACL(JG,JK,JL,JB)=0.99_JPRB
          ZGCL(JG,JK,JL,JB)=0.7_JPRB
        ENDDO
      ENDDO
    ENDDO
  ENDDO
  CALL YDWORK1%INIT(KLEV,KCOL,KBLOCK,IG,1)
  CALL YDWORK2%INIT(KLEV,KCOL,KBLOCK,IG,2)
  !$ACC ENTER DATA COPYIN(YLCONFIG)
  !$ACC ENTER DATA COPYIN(YLCONFIG%I_BAND_FROM_REORDERED_G_SW,YLCONFIG%PDF_SAMPLER%VAL)
  !$ACC DATA COPYIN(ZMU,ZFSD,ZOVER,ZOD,ZSSA,ZG,ZODCL,ZSSACL,ZGCL,ZALBD,ZALBF,ZINCOMING) &
  !$ACC& CREATE(IFIRST,ILAST,ISEED,ZCLOUD,ZCOVER,ZSURF,ZFLUX,ZCOVER2,ZSURF2,ZFLUX2,ZREFC,ZREFS,ZREFF)
  DO IREPEAT=1,4
    YLCONFIG%CLOUD_FRACTION_THRESHOLD=1.0E-6_JPRB
    IF (IREPEAT == 4) YLCONFIG%CLOUD_FRACTION_THRESHOLD=0.02_JPRB
    DO JB=1,KBLOCK
      IFIRST(JB)=2
      ILAST(JB)=KCOL-1
      IF (IREPEAT == 2 .AND. JB == 2) ILAST(JB)=1
      DO JL=1,KCOL
        ISEED(JL,JB,1)=100+JL+KCOL*JB+IREPEAT*97
        ISEED(JL,JB,2)=ISEED(JL,JB,1)+4999
        DO JK=1,KLEV
          ZCLOUD(JL,JK,JB)=0.1_JPRB*MOD(JK+JL+JB+IREPEAT,9)
          IF (MOD(JL+IREPEAT,4) == 0) ZCLOUD(JL,JK,JB)=0.0_JPRB
          IF (MOD(JL+IREPEAT,7) == 0) ZCLOUD(JL,JK,JB)=1.0_JPRB
        ENDDO
      ENDDO
    ENDDO
    ZCOVER(:,:)=ZPOISON
    ZCOVER2(:,:)=ZPOISON
    ZREFC(:,:,:)=ZPOISON
    ZSURF(:,:,:,:)=ZPOISON
    ZSURF2(:,:,:,:)=ZPOISON
    ZREFS(:,:,:,:,:)=ZPOISON
    ZFLUX(:,:,:,:)=ZPOISON
    ZFLUX2(:,:,:,:)=ZPOISON
    ZREFF(:,:,:,:,:)=ZPOISON
    !$ACC UPDATE DEVICE(IFIRST,ILAST,ISEED,ZCLOUD,ZCOVER,ZSURF,ZFLUX,ZCOVER2,ZSURF2,ZFLUX2,ZREFC,ZREFS,ZREFF)
    CALL YDWORK1%INIT(KLEV,KCOL,KBLOCK,IG,1)
    CALL SOLVE_SW_BATCH(YDWORK1,YLCONFIG,KACTIVE,IFIRST,ILAST,ISEED(:,:,1),ZMU,ZCLOUD,ZFSD,ZOVER, &
      & ZOD,ZSSA,ZG,ZODCL,ZSSACL,ZGCL,ZALBD,ZALBF,ZINCOMING,ZCOVER,ZSURF,ZFLUX)
    CALL SOLVE_SW_BATCH(YDWORK2,YLCONFIG,KACTIVE,IFIRST,ILAST,ISEED(:,:,2),ZMU,ZCLOUD,ZFSD,ZOVER, &
      & ZOD,ZSSA,ZG,ZODCL,ZSSACL,ZGCL,ZALBD,ZALBF,ZINCOMING,ZCOVER2,ZSURF2,ZFLUX2)
    !$ACC WAIT
    DO IQ=1,2
      DO JB=1,KACTIVE
      IF (ILAST(JB) < IFIRST(JB)) CYCLE
      CALL SOLVER_MCICA_ACC_GPOINT_SW_IMPL(KLEV,KCOL,IFIRST(JB),ILAST(JB),IG,INCDF,INFSD,IBAND, &
        & LDBETA,.FALSE.,YLCONFIG%CLOUD_FRACTION_THRESHOLD,YLCONFIG%CLOUD_INHOM_DECORR_SCALING, &
        & YLCONFIG%PDF_SAMPLER%FSD1,YLCONFIG%PDF_SAMPLER%INV_FSD_INTERVAL, &
        & YLCONFIG%I_BAND_FROM_REORDERED_G_SW,YLCONFIG%PDF_SAMPLER%VAL,ISEED(:,JB,IQ),ZMU(:,JB), &
        & ZCLOUD(:,:,JB),ZFSD(:,:,JB),ZOVER(:,:,JB), &
        & ZOD(:,:,IFIRST(JB):ILAST(JB),JB),ZSSA(:,:,IFIRST(JB):ILAST(JB),JB),ZG(:,:,IFIRST(JB):ILAST(JB),JB), &
        & ZODCL(:,:,IFIRST(JB):ILAST(JB),JB),ZSSACL(:,:,IFIRST(JB):ILAST(JB),JB), &
        & ZGCL(:,:,IFIRST(JB):ILAST(JB),JB),ZALBD(:,IFIRST(JB):ILAST(JB),JB), &
        & ZALBF(:,IFIRST(JB):ILAST(JB),JB),ZINCOMING(:,IFIRST(JB):ILAST(JB),JB), &
        & ZREFC(:,JB,IQ),ZREFS(:,:,JB,1,IQ),ZREFS(:,:,JB,2,IQ),ZREFS(:,:,JB,3,IQ),ZREFS(:,:,JB,4,IQ), &
        & ZREFF(:,:,JB,1,IQ),ZREFF(:,:,JB,2,IQ),ZREFF(:,:,JB,3,IQ),ZREFF(:,:,JB,4,IQ), &
        & SW_DN_DIRECT=ZREFF(:,:,JB,5,IQ),SW_DN_DIRECT_CLEAR=ZREFF(:,:,JB,6,IQ))
      ENDDO
    ENDDO
    !$ACC UPDATE HOST(ZCOVER,ZSURF,ZFLUX,ZCOVER2,ZSURF2,ZFLUX2,ZREFC,ZREFS,ZREFF)
    IF (.NOT. ALL(IEEE_IS_FINITE(ZCOVER)) .OR. .NOT. ALL(IEEE_IS_FINITE(ZSURF)) &
      & .OR. .NOT. ALL(IEEE_IS_FINITE(ZFLUX)) .OR. .NOT. ALL(IEEE_IS_FINITE(ZCOVER2)) &
      & .OR. .NOT. ALL(IEEE_IS_FINITE(ZSURF2)) .OR. .NOT. ALL(IEEE_IS_FINITE(ZFLUX2))) &
      & CALL ABOR1('SW batch: nonfinite output')
    IF (ANY(ZCOVER /= ZREFC(:,:,1)) .OR. ANY(ZCOVER2 /= ZREFC(:,:,2))) &
      & CALL ABOR1('SW batch: cover/masks differ')
    ZERROR=MAX(MAXVAL(ABS(ZSURF-ZREFS(:,:,:,:,1))),MAXVAL(ABS(ZFLUX-ZREFF(:,:,:,:,1))), &
      & MAXVAL(ABS(ZSURF2-ZREFS(:,:,:,:,2))),MAXVAL(ABS(ZFLUX2-ZREFF(:,:,:,:,2))))
    IF (.NOT. IEEE_IS_FINITE(ZERROR) .OR. ZERROR > ZTOL) CALL ABOR1('SW batch: reference flux mismatch')
    ! Inactive blocks/columns must remain bit-exact poison, not just within tolerance.
    DO JB=1,KBLOCK
      DO JL=1,KCOL
        IF (JB > KACTIVE .OR. JL < IFIRST(JB) .OR. JL > ILAST(JB)) THEN
          IF (ZCOVER(JL,JB) /= ZPOISON .OR. ANY(ZSURF(:,JL,JB,:) /= ZPOISON) &
            & .OR. ANY(ZFLUX(JL,:,JB,:) /= ZPOISON) .OR. ZCOVER2(JL,JB) /= ZPOISON &
            & .OR. ANY(ZSURF2(:,JL,JB,:) /= ZPOISON) .OR. ANY(ZFLUX2(JL,:,JB,:) /= ZPOISON)) &
            & CALL ABOR1('SW batch: inactive region overwritten')
        ELSEIF (ZMU(JL,JB) <= 0.0_JPRB) THEN
          IF (ZCOVER(JL,JB) /= 0.0_JPRB .OR. ANY(ZSURF(:,JL,JB,:) /= 0.0_JPRB) &
            & .OR. ANY(ZFLUX(JL,:,JB,:) /= 0.0_JPRB) .OR. ZCOVER2(JL,JB) /= 0.0_JPRB &
            & .OR. ANY(ZSURF2(:,JL,JB,:) /= 0.0_JPRB) .OR. ANY(ZFLUX2(JL,:,JB,:) /= 0.0_JPRB)) &
            & CALL ABOR1('SW batch: nonzero nighttime output')
        ENDIF
      ENDDO
    ENDDO
    WRITE(NULOUT,'(A,5I5,L2,A,ES12.4)') 'SW batch case ',KLEV,KCOL,KBLOCK,KACTIVE,IREPEAT,LDBETA, &
      & ' max flux error=',ZERROR
  ENDDO
  !$ACC END DATA
  !$ACC EXIT DATA DELETE(YLCONFIG%I_BAND_FROM_REORDERED_G_SW,YLCONFIG%PDF_SAMPLER%VAL)
  !$ACC EXIT DATA DELETE(YLCONFIG)
  IF (LHOOK) CALL DR_HOOK('TEST_SW_BATCH%RUN_CASE',1,ZHOOK_HANDLE)
END SUBROUTINE RUN_CASE

END PROGRAM TEST_SW_BATCH
