! Test-only link interposition at the existing SW solver public interface.
! The original numerical core is compiled under a separate module name.
MODULE RADIATION_MCICA_ACC_GPOINT_SW
  USE PARKIND1, ONLY : JPIM,JPRB
  USE YOMHOOK, ONLY : LHOOK,DR_HOOK,JPHOOK
  IMPLICIT NONE
CONTAINS
SUBROUTINE SOLVER_MCICA_ACC_GPOINT_SW(KLEV,KFIRST,KLAST,YDCONFIG,YDSINGLE,YDCLOUD, &
  & POD,PSSA,PG,PODCL,PSSACL,PGCL,PALBD,PALBF,PINCOMING,YDFLUX)
  USE RADIATION_CONFIG, ONLY : CONFIG_TYPE
  USE RADIATION_SINGLE_LEVEL, ONLY : SINGLE_LEVEL_TYPE
  USE RADIATION_CLOUD, ONLY : CLOUD_TYPE
  USE RADIATION_FLUX, ONLY : FLUX_TYPE
  USE RADIATION_MCICA_SW_BATCH_REFERENCE, ONLY : SOLVER_MCICA_ACC_GPOINT_SW_IMPL
  INTEGER(KIND=JPIM), INTENT(IN) :: KLEV,KFIRST,KLAST
  TYPE(CONFIG_TYPE), INTENT(IN) :: YDCONFIG
  TYPE(SINGLE_LEVEL_TYPE), INTENT(IN) :: YDSINGLE
  TYPE(CLOUD_TYPE), INTENT(IN) :: YDCLOUD
  REAL(KIND=JPRB), INTENT(IN) :: POD(YDCONFIG%N_G_SW,KLEV,KFIRST:KLAST)
  REAL(KIND=JPRB), INTENT(IN) :: PSSA(YDCONFIG%N_G_SW,KLEV,KFIRST:KLAST)
  REAL(KIND=JPRB), INTENT(IN) :: PG(YDCONFIG%N_G_SW,KLEV,KFIRST:KLAST)
  REAL(KIND=JPRB), INTENT(IN) :: PODCL(YDCONFIG%N_BANDS_SW,KLEV,KFIRST:KLAST)
  REAL(KIND=JPRB), INTENT(IN) :: PSSACL(YDCONFIG%N_BANDS_SW,KLEV,KFIRST:KLAST)
  REAL(KIND=JPRB), INTENT(IN) :: PGCL(YDCONFIG%N_BANDS_SW,KLEV,KFIRST:KLAST)
  REAL(KIND=JPRB), INTENT(IN) :: PALBD(YDCONFIG%N_G_SW,KFIRST:KLAST),PALBF(YDCONFIG%N_G_SW,KFIRST:KLAST)
  REAL(KIND=JPRB), INTENT(IN) :: PINCOMING(YDCONFIG%N_G_SW,KFIRST:KLAST)
  TYPE(FLUX_TYPE), INTENT(INOUT) :: YDFLUX
  INTEGER(KIND=JPIM) :: ICOL,IUNIT,ISTATUS
  CHARACTER(LEN=1024) :: YLPATH
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
#include "abor1.intfb.h"
  IF (LHOOK) CALL DR_HOOK('CAPTURE_SW',0,ZHOOK_HANDLE)
  ICOL=SIZE(YDCLOUD%FRACTION,1)
  IF (STORAGE_SIZE(1.0_JPRB) /= 32 .OR. KFIRST /= 1 .OR. KLAST /= ICOL) &
    & CALL ABOR1('CAPTURE_SW: expected full SP blocks')
  IF (.NOT. YDCONFIG%DO_CLEAR .OR. YDCONFIG%DO_SW_DELTA_SCALING_WITH_GASES) &
    & CALL ABOR1('CAPTURE_SW: unsupported pilot configuration')
  CALL GET_ENVIRONMENT_VARIABLE('ECRAD_SW_FIXTURE',YLPATH,STATUS=ISTATUS)
  IF (ISTATUS /= 0 .OR. LEN_TRIM(YLPATH) == 0) CALL ABOR1('CAPTURE_SW: missing fixture path')
  CALL SOLVER_MCICA_ACC_GPOINT_SW_IMPL(KLEV,ICOL,KFIRST,KLAST,YDCONFIG%N_G_SW, &
    & YDCONFIG%PDF_SAMPLER%NCDF,YDCONFIG%PDF_SAMPLER%NFSD,YDCONFIG%N_BANDS_SW, &
    & YDCONFIG%USE_BETA_OVERLAP,YDCONFIG%DO_SW_DELTA_SCALING_WITH_GASES, &
    & YDCONFIG%CLOUD_FRACTION_THRESHOLD,YDCONFIG%CLOUD_INHOM_DECORR_SCALING, &
    & YDCONFIG%PDF_SAMPLER%FSD1,YDCONFIG%PDF_SAMPLER%INV_FSD_INTERVAL, &
    & YDCONFIG%I_BAND_FROM_REORDERED_G_SW,YDCONFIG%PDF_SAMPLER%VAL,YDSINGLE%ISEED,YDSINGLE%COS_SZA, &
    & YDCLOUD%FRACTION,YDCLOUD%FRACTIONAL_STD,YDCLOUD%OVERLAP_PARAM, &
    & POD,PSSA,PG,PODCL,PSSACL,PGCL,PALBD,PALBF,PINCOMING, &
    & YDFLUX%CLOUD_COVER_SW,YDFLUX%SW_DN_DIFFUSE_SURF_CLEAR_G,YDFLUX%SW_DN_DIRECT_SURF_CLEAR_G, &
    & YDFLUX%SW_DN_DIFFUSE_SURF_G,YDFLUX%SW_DN_DIRECT_SURF_G, &
    & YDFLUX%SW_UP_CLEAR,YDFLUX%SW_DN_CLEAR,YDFLUX%SW_UP,YDFLUX%SW_DN, &
    & SW_DN_DIRECT=YDFLUX%SW_DN_DIRECT,SW_DN_DIRECT_CLEAR=YDFLUX%SW_DN_DIRECT_CLEAR)
  !$ACC UPDATE SELF(POD,PSSA,PG,PODCL,PSSACL,PGCL,PALBD,PALBF,PINCOMING)
  !$ACC UPDATE SELF(YDSINGLE%ISEED,YDSINGLE%COS_SZA,YDCLOUD%FRACTION,YDCLOUD%FRACTIONAL_STD,YDCLOUD%OVERLAP_PARAM)
  !$ACC UPDATE SELF(YDFLUX%CLOUD_COVER_SW,YDFLUX%SW_DN_DIFFUSE_SURF_CLEAR_G,YDFLUX%SW_DN_DIRECT_SURF_CLEAR_G)
  !$ACC UPDATE SELF(YDFLUX%SW_DN_DIFFUSE_SURF_G,YDFLUX%SW_DN_DIRECT_SURF_G)
  !$ACC UPDATE SELF(YDFLUX%SW_UP_CLEAR,YDFLUX%SW_DN_CLEAR,YDFLUX%SW_UP,YDFLUX%SW_DN)
  !$ACC UPDATE SELF(YDFLUX%SW_DN_DIRECT,YDFLUX%SW_DN_DIRECT_CLEAR)
  OPEN(NEWUNIT=IUNIT,FILE=TRIM(YLPATH),FORM='UNFORMATTED',ACCESS='STREAM',STATUS='UNKNOWN',POSITION='APPEND')
  WRITE(IUNIT) 20261020,STORAGE_SIZE(1.0_JPRB),KLEV,ICOL,KFIRST,KLAST, &
    & YDCONFIG%N_G_SW,YDCONFIG%N_BANDS_SW,YDCONFIG%PDF_SAMPLER%NCDF,YDCONFIG%PDF_SAMPLER%NFSD
  WRITE(IUNIT) YDCONFIG%USE_BETA_OVERLAP,YDCONFIG%CLOUD_FRACTION_THRESHOLD, &
    & YDCONFIG%CLOUD_INHOM_DECORR_SCALING,YDCONFIG%PDF_SAMPLER%FSD1,YDCONFIG%PDF_SAMPLER%INV_FSD_INTERVAL, &
    & YDCONFIG%I_BAND_FROM_REORDERED_G_SW,YDCONFIG%PDF_SAMPLER%VAL
  WRITE(IUNIT) YDSINGLE%ISEED,YDSINGLE%COS_SZA,YDCLOUD%FRACTION,YDCLOUD%FRACTIONAL_STD,YDCLOUD%OVERLAP_PARAM, &
    & POD,PSSA,PG,PODCL,PSSACL,PGCL,PALBD,PALBF,PINCOMING, &
    & YDFLUX%CLOUD_COVER_SW,YDFLUX%SW_DN_DIFFUSE_SURF_CLEAR_G,YDFLUX%SW_DN_DIRECT_SURF_CLEAR_G, &
    & YDFLUX%SW_DN_DIFFUSE_SURF_G,YDFLUX%SW_DN_DIRECT_SURF_G, &
    & YDFLUX%SW_UP_CLEAR,YDFLUX%SW_DN_CLEAR,YDFLUX%SW_UP,YDFLUX%SW_DN, &
    & YDFLUX%SW_DN_DIRECT,YDFLUX%SW_DN_DIRECT_CLEAR
  CLOSE(IUNIT)
  IF (LHOOK) CALL DR_HOOK('CAPTURE_SW',1,ZHOOK_HANDLE)
END SUBROUTINE SOLVER_MCICA_ACC_GPOINT_SW
END MODULE RADIATION_MCICA_ACC_GPOINT_SW
