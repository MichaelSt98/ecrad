MODULE SW_REPLAY_IO_MOD
  USE PARKIND1, ONLY : JPIM,JPRB
  USE YOMHOOK, ONLY : LHOOK,DR_HOOK,JPHOOK
  USE RADIATION_CONFIG, ONLY : CONFIG_TYPE
  IMPLICIT NONE
  PRIVATE
  PUBLIC :: SW_REPLAY_BLOCK_TYPE,READ_SW_RECORD
  INTEGER(KIND=JPIM), PARAMETER :: IMAGIC=20261020
  TYPE SW_REPLAY_BLOCK_TYPE
    INTEGER(KIND=JPIM) :: NLEV,NCOL,NG,NBAND,FIRST,LAST
    INTEGER(KIND=JPIM), ALLOCATABLE :: SEED(:)
    REAL(KIND=JPRB), ALLOCATABLE :: MU(:),CLOUD(:,:,:),OVERLAP(:,:)
    REAL(KIND=JPRB), ALLOCATABLE :: OPT(:,:,:,:),COPT(:,:,:,:),BOUNDARY(:,:,:)
    REAL(KIND=JPRB), ALLOCATABLE :: COVER(:),SURFACE(:,:,:),FLUX(:,:,:)
  END TYPE SW_REPLAY_BLOCK_TYPE
CONTAINS
SUBROUTINE READ_SW_RECORD(KUNIT,YDBLOCK,YDCONFIG,KSTATUS)
  INTEGER(KIND=JPIM), INTENT(IN) :: KUNIT
  TYPE(SW_REPLAY_BLOCK_TYPE), INTENT(OUT) :: YDBLOCK
  TYPE(CONFIG_TYPE), INTENT(INOUT) :: YDCONFIG
  INTEGER(KIND=JPIM), INTENT(OUT) :: KSTATUS
  INTEGER(KIND=JPIM) :: IHEADER(10),IMAP_SIZE,INCDF,INFSD
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
#include "abor1.intfb.h"
  IF (LHOOK) CALL DR_HOOK('READ_SW_RECORD',0,ZHOOK_HANDLE)
  READ(KUNIT,IOSTAT=KSTATUS) IHEADER
  IF (KSTATUS == 0) THEN
    IF (IHEADER(1) /= IMAGIC .OR. IHEADER(2) /= STORAGE_SIZE(1.0_JPRB)) &
      & CALL ABOR1('READ_SW_RECORD: wrong fixture version/precision')
    YDBLOCK%NLEV=IHEADER(3)
    YDBLOCK%NCOL=IHEADER(4)
    YDBLOCK%FIRST=IHEADER(5)
    YDBLOCK%LAST=IHEADER(6)
    YDBLOCK%NG=IHEADER(7)
    YDBLOCK%NBAND=IHEADER(8)
    INCDF=IHEADER(9)
    INFSD=IHEADER(10)
    IF (YDBLOCK%FIRST /= 1 .OR. YDBLOCK%LAST /= YDBLOCK%NCOL) &
      & CALL ABOR1('READ_SW_RECORD: focused experiment requires full model blocks')
    IF (ALLOCATED(YDCONFIG%I_BAND_FROM_REORDERED_G_SW)) DEALLOCATE(YDCONFIG%I_BAND_FROM_REORDERED_G_SW)
    IF (ALLOCATED(YDCONFIG%PDF_SAMPLER%VAL)) DEALLOCATE(YDCONFIG%PDF_SAMPLER%VAL)
    YDCONFIG%N_G_SW=YDBLOCK%NG
    YDCONFIG%N_BANDS_SW=YDBLOCK%NBAND
    YDCONFIG%DO_CLEAR=.TRUE.
    YDCONFIG%DO_SW_DELTA_SCALING_WITH_GASES=.FALSE.
    YDCONFIG%PDF_SAMPLER%NCDF=INCDF
    YDCONFIG%PDF_SAMPLER%NFSD=INFSD
    IMAP_SIZE=YDBLOCK%NG
    ALLOCATE(YDCONFIG%I_BAND_FROM_REORDERED_G_SW(IMAP_SIZE),YDCONFIG%PDF_SAMPLER%VAL(INCDF,INFSD))
    READ(KUNIT) YDCONFIG%USE_BETA_OVERLAP,YDCONFIG%CLOUD_FRACTION_THRESHOLD, &
      & YDCONFIG%CLOUD_INHOM_DECORR_SCALING,YDCONFIG%PDF_SAMPLER%FSD1,YDCONFIG%PDF_SAMPLER%INV_FSD_INTERVAL, &
      & YDCONFIG%I_BAND_FROM_REORDERED_G_SW,YDCONFIG%PDF_SAMPLER%VAL
    ALLOCATE(YDBLOCK%SEED(YDBLOCK%NCOL),YDBLOCK%MU(YDBLOCK%NCOL))
    ALLOCATE(YDBLOCK%CLOUD(YDBLOCK%NCOL,YDBLOCK%NLEV,2),YDBLOCK%OVERLAP(YDBLOCK%NCOL,YDBLOCK%NLEV-1))
    ALLOCATE(YDBLOCK%OPT(YDBLOCK%NG,YDBLOCK%NLEV,YDBLOCK%NCOL,3))
    ALLOCATE(YDBLOCK%COPT(YDBLOCK%NBAND,YDBLOCK%NLEV,YDBLOCK%NCOL,3))
    ALLOCATE(YDBLOCK%BOUNDARY(YDBLOCK%NG,YDBLOCK%NCOL,3),YDBLOCK%COVER(YDBLOCK%NCOL))
    ALLOCATE(YDBLOCK%SURFACE(YDBLOCK%NG,YDBLOCK%NCOL,4),YDBLOCK%FLUX(YDBLOCK%NCOL,YDBLOCK%NLEV+1,6))
    READ(KUNIT) YDBLOCK%SEED,YDBLOCK%MU,YDBLOCK%CLOUD,YDBLOCK%OVERLAP, &
      & YDBLOCK%OPT,YDBLOCK%COPT,YDBLOCK%BOUNDARY,YDBLOCK%COVER,YDBLOCK%SURFACE,YDBLOCK%FLUX
  ENDIF
  IF (LHOOK) CALL DR_HOOK('READ_SW_RECORD',1,ZHOOK_HANDLE)
END SUBROUTINE READ_SW_RECORD
END MODULE SW_REPLAY_IO_MOD
