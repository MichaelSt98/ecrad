PROGRAM BENCH_SW_REPLAY
  USE PARKIND1, ONLY : JPIM,JPRB
  USE RADIATION_CONFIG, ONLY : CONFIG_TYPE
  USE RADIATION_IO, ONLY : NULOUT
  USE SW_REPLAY_IO_MOD, ONLY : SW_REPLAY_BLOCK_TYPE,READ_SW_RECORD
  USE SW_REPLAY_BENCH_MOD, ONLY : MEASURE_SW_REPLAY
  IMPLICIT NONE
  TYPE(SW_REPLAY_BLOCK_TYPE), ALLOCATABLE :: YLDOMAIN(:)
  TYPE(SW_REPLAY_BLOCK_TYPE) :: YLEXTRA
  TYPE(CONFIG_TYPE) :: YLCONFIG,YLCHECK
  INTEGER(KIND=JPIM) :: IUNIT,ISTATUS,JB,IMODE,ICAP,IBOUNDARY,IREPEAT
  CHARACTER(LEN=1024) :: YLPATH,YLARG
#include "abor1.intfb.h"
  IF (COMMAND_ARGUMENT_COUNT() /= 5) CALL ABOR1('Usage: replay fixture mode K boundary repetitions')
  CALL GET_COMMAND_ARGUMENT(1,YLPATH)
  CALL GET_COMMAND_ARGUMENT(2,YLARG)
  READ(YLARG,*) IMODE
  CALL GET_COMMAND_ARGUMENT(3,YLARG)
  READ(YLARG,*) ICAP
  CALL GET_COMMAND_ARGUMENT(4,YLARG)
  READ(YLARG,*) IBOUNDARY
  CALL GET_COMMAND_ARGUMENT(5,YLARG)
  READ(YLARG,*) IREPEAT
  IF (STORAGE_SIZE(1.0_JPRB) /= 32) CALL ABOR1('BENCH_SW_REPLAY: SP executable required')
  IF (IMODE < 0 .OR. IMODE > 1 .OR. IBOUNDARY < 0 .OR. IBOUNDARY > 1) CALL ABOR1('Invalid mode/boundary')
  ALLOCATE(YLDOMAIN(530))
  OPEN(NEWUNIT=IUNIT,FILE=TRIM(YLPATH),FORM='UNFORMATTED',ACCESS='STREAM',STATUS='OLD')
  CALL READ_SW_RECORD(IUNIT,YLDOMAIN(1),YLCONFIG,ISTATUS)
  IF (ISTATUS /= 0) CALL ABOR1('BENCH_SW_REPLAY: missing first block')
  DO JB=2,SIZE(YLDOMAIN)
    CALL READ_SW_RECORD(IUNIT,YLDOMAIN(JB),YLCHECK,ISTATUS)
    IF (ISTATUS /= 0) CALL ABOR1('BENCH_SW_REPLAY: incomplete fixture')
    IF (YLDOMAIN(JB)%NLEV /= 137 .OR. YLDOMAIN(JB)%NCOL /= 32 &
      & .OR. YLDOMAIN(JB)%NG /= YLDOMAIN(1)%NG .OR. YLDOMAIN(JB)%NBAND /= YLDOMAIN(1)%NBAND) &
      & CALL ABOR1('BENCH_SW_REPLAY: nonhomogeneous block shapes')
    IF (YLCHECK%PDF_SAMPLER%NCDF /= YLCONFIG%PDF_SAMPLER%NCDF &
      & .OR. YLCHECK%PDF_SAMPLER%NFSD /= YLCONFIG%PDF_SAMPLER%NFSD) &
      & CALL ABOR1('BENCH_SW_REPLAY: PDF shape changed')
    IF (ANY(YLCHECK%PDF_SAMPLER%VAL /= YLCONFIG%PDF_SAMPLER%VAL) &
      & .OR. ANY(YLCHECK%I_BAND_FROM_REORDERED_G_SW /= YLCONFIG%I_BAND_FROM_REORDERED_G_SW) &
      & .OR. (YLCHECK%USE_BETA_OVERLAP .NEQV. YLCONFIG%USE_BETA_OVERLAP)) &
      & CALL ABOR1('BENCH_SW_REPLAY: coefficient tables changed')
    IF (YLCHECK%CLOUD_FRACTION_THRESHOLD /= YLCONFIG%CLOUD_FRACTION_THRESHOLD &
      & .OR. YLCHECK%CLOUD_INHOM_DECORR_SCALING /= YLCONFIG%CLOUD_INHOM_DECORR_SCALING &
      & .OR. YLCHECK%PDF_SAMPLER%FSD1 /= YLCONFIG%PDF_SAMPLER%FSD1 &
      & .OR. YLCHECK%PDF_SAMPLER%INV_FSD_INTERVAL /= YLCONFIG%PDF_SAMPLER%INV_FSD_INTERVAL) &
      & CALL ABOR1('BENCH_SW_REPLAY: scalar configuration changed')
  ENDDO
  CALL READ_SW_RECORD(IUNIT,YLEXTRA,YLCHECK,ISTATUS)
  IF (ISTATUS >= 0) CALL ABOR1('BENCH_SW_REPLAY: expected EOF after exactly 530 blocks')
  CLOSE(IUNIT)
  WRITE(NULOUT,'(A,4I8)') 'FIXTURE ',SIZE(YLDOMAIN),YLDOMAIN(1)%NCOL,YLDOMAIN(1)%NLEV,YLDOMAIN(1)%NG
  CALL MEASURE_SW_REPLAY(YLDOMAIN,YLCONFIG,IMODE,ICAP,IBOUNDARY,IREPEAT)
END PROGRAM BENCH_SW_REPLAY
