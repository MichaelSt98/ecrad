PROGRAM MINSTD_INTEGER
  USE PARKIND1, ONLY : JPIB, JPIM, JPRB, JPRM, JPRD
  USE RADIATION_RANDOM_NUMBERS, ONLY : ADVANCE_MINSTD_INTEGER
  USE RADIATION_IO, ONLY : RADIATION_ABORT
  USE YOMHOOK, ONLY : LHOOK, DR_HOOK, JPHOOK
  IMPLICIT NONE
  INTEGER(JPIB), PARAMETER :: IMODULUS = 2147483647_JPIB
  INTEGER(JPIB), PARAMETER :: ISTART(9) = &
    & [-2147483648_JPIB,-IMODULUS,-IMODULUS+1_JPIB,-1_JPIB,0_JPIB, &
    & 1_JPIB,IMODULUS-1_JPIB,IMODULUS,2147483648_JPIB]
  INTEGER(JPIB) :: ISTATE, IEXPECTED, IACTUAL
  INTEGER(JPIM) :: JSEED, JDRAW
  REAL(JPHOOK) :: ZHOOK_HANDLE

  IF (LHOOK) CALL DR_HOOK('MINSTD_INTEGER',0,ZHOOK_HANDLE)
  ! NVHPC searches its module output directory before include directories.
  ! Catch accidental SP-module imports in a mixed-precision DP test build.
#ifdef PARKIND1_SINGLE
  IF (JPRB /= JPRM) CALL RADIATION_ABORT('MINSTD_INTEGER: expected SP PARKIND1 module')
#else
  IF (JPRB /= JPRD) CALL RADIATION_ABORT('MINSTD_INTEGER: expected DP PARKIND1 module')
#endif
  DO JSEED = 1,SIZE(ISTART)
    ISTATE = ISTART(JSEED)
    DO JDRAW = 1,100000
      ! Compare against the original floating-state arithmetic, including
      ! negative states, zero, the modulus and SP seed-rounding boundaries.
      IEXPECTED = INT(MOD(48271.0_JPRD*REAL(ISTATE,JPRD),REAL(IMODULUS,JPRD)),JPIB)
      IACTUAL = ADVANCE_MINSTD_INTEGER(ISTATE)
      IF (IACTUAL /= IEXPECTED) THEN
        CALL RADIATION_ABORT('MINSTD_INTEGER: sequence differs from floating MOD')
      ENDIF
      ISTATE = IEXPECTED
    ENDDO
  ENDDO
  IF (LHOOK) CALL DR_HOOK('MINSTD_INTEGER',1,ZHOOK_HANDLE)
END PROGRAM MINSTD_INTEGER
