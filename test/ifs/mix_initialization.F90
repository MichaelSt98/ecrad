PROGRAM MIX_INITIALIZATION
  USE PARKIND1, ONLY : JPIM, JPRB
  USE RADIATION_RANDOM_NUMBERS_MIX, ONLY : RANDOMNUMBERSTREAM, &
    & INITIALIZE_RANDOM_NUMBERS, UNIFORM_DISTRIBUTION
  USE RADIATION_IO, ONLY : RADIATION_ABORT
  USE YOMHOOK, ONLY : LHOOK, DR_HOOK, JPHOOK
  IMPLICIT NONE
  INTEGER(JPIM), PARAMETER :: ISEEDS(7) = [0_JPIM,1_JPIM,-1_JPIM,123459876_JPIM, &
    & HUGE(0_JPIM),-HUGE(0_JPIM),IEOR(-HUGE(0_JPIM)-1_JPIM,123459876_JPIM)]
  INTEGER(JPIM), PARAMETER :: IMAP(7) = [1_JPIM,2_JPIM,2_JPIM,1_JPIM,3_JPIM,3_JPIM,4_JPIM]
  ! First post-warmup words from the original generator at pinned main
  ! 54fe9cb7. Compare public outputs, not a second implementation of the
  ! optimized shift loop. Include zero-mask fallback and signed boundaries.
  INTEGER(JPIM), PARAMETER :: IWORDS(16,4) = RESHAPE([ &
    & 332454828,106119784,1007079490,306981660,593672722,699494866,850072136,908347670, &
    & 223326252,963068338,328939454,699911632,14761060,29634556,860668858,171780114, &
    & 892970050,512731692,295823498,924008444,777153096,91864458,365936434,390209068, &
    & 90595642,146723700,244127092,703046622,4917594,580764172,879210360,428118324, &
    & 372488558,592082738,51173224,1030369464,314128780,682559718,958242394,525440632, &
    & 757198558,631879674,174936790,826289202,966253480,316242824,341012626,691351214, &
    & 360797274,314216852,843045550,1022919686,634772864,267557406,717949958,395161482, &
    & 239304828,328474810,498229072,519806152,310886346,763100804,881335226,835019502], [16,4])
  TYPE(RANDOMNUMBERSTREAM) :: YSTREAM
  REAL(JPRB) :: ZACTUAL(16), ZEXPECTED(16)
  INTEGER(JPIM) :: JSEED
  REAL(JPHOOK) :: ZHOOK_HANDLE

  IF (LHOOK) CALL DR_HOOK('MIX_INITIALIZATION',0,ZHOOK_HANDLE)
  DO JSEED = 1,SIZE(ISEEDS)
    CALL INITIALIZE_RANDOM_NUMBERS(ISEEDS(JSEED),YSTREAM)
    CALL UNIFORM_DISTRIBUTION(ZACTUAL,YSTREAM)
    ZEXPECTED = REAL(IWORDS(:,IMAP(JSEED)),JPRB)/1073741824.0_JPRB
    IF (ANY(ZACTUAL /= ZEXPECTED)) THEN
      CALL RADIATION_ABORT('MIX_INITIALIZATION: original random stream changed')
    ENDIF
  ENDDO
  IF (LHOOK) CALL DR_HOOK('MIX_INITIALIZATION',1,ZHOOK_HANDLE)
END PROGRAM MIX_INITIALIZATION
