    & LW_DERIVATIVES=YD%LW_DERIV)
  IF (YD%PROFILE) CALL YD%PROFILE_MARK(10,.FALSE.)
  IF (LHOOK) CALL DR_HOOK('SW_BATCH_CONTEXT%SOLVE_LW',1,ZHOOK_HANDLE)
END SUBROUTINE SOLVE_LW

SUBROUTINE SCATTER_LW(YD,KSLOT,YDFLUX)
  CLASS(SW_BATCH_CONTEXT_TYPE), INTENT(INOUT) :: YD
  INTEGER(KIND=JPIM), INTENT(IN) :: KSLOT
  TYPE(FLUX_TYPE), INTENT(INOUT) :: YDFLUX
  INTEGER(KIND=JPIM) :: JL,JK,JG,ICOL,IOFFSET
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('SW_BATCH_CONTEXT%SCATTER_LW',0,ZHOOK_HANDLE)
  IF (YD%PROFILE) CALL YD%PROFILE_MARK(11,.TRUE.)
  IF (.NOT. YD%SOLVED) CALL ABOR1('LW tile: scatter before solve')
  IOFFSET=(KSLOT-1)*YD%NCOL
  !$ACC PARALLEL LOOP COLLAPSE(2) GANG VECTOR DEFAULT(PRESENT) ASYNC(1)
  DO JK=1,YD%NLEV+1
    DO JL=YD%FIRST(KSLOT),YD%LAST(KSLOT)
      ICOL=IOFFSET+JL
      YDFLUX%LW_UP_CLEAR(JL,JK)=YD%LW_FLUX(ICOL,JK,1)
      YDFLUX%LW_DN_CLEAR(JL,JK)=YD%LW_FLUX(ICOL,JK,2)
      YDFLUX%LW_UP(JL,JK)=YD%LW_FLUX(ICOL,JK,3)
      YDFLUX%LW_DN(JL,JK)=YD%LW_FLUX(ICOL,JK,4)
      IF (YD%LW_DERIVATIVES) YDFLUX%LW_DERIVATIVES(JL,JK)=YD%LW_DERIV(ICOL,JK)
      IF (JK == 1) YDFLUX%CLOUD_COVER_LW(JL)=YD%LW_COVER(ICOL)
    ENDDO
  ENDDO
  !$ACC PARALLEL LOOP COLLAPSE(2) GANG VECTOR DEFAULT(PRESENT) ASYNC(1)
  DO JL=YD%FIRST(KSLOT),YD%LAST(KSLOT)
    DO JG=1,YD%LW_NG
      ICOL=IOFFSET+JL
      YDFLUX%LW_DN_SURF_CLEAR_G(JG,JL)=YD%LW_SURFACE(JG,ICOL,1)
      YDFLUX%LW_DN_SURF_G(JG,JL)=YD%LW_SURFACE(JG,ICOL,2)
    ENDDO
  ENDDO
  IF (YD%PROFILE) CALL YD%PROFILE_MARK(11,.FALSE.)
  IF (LHOOK) CALL DR_HOOK('SW_BATCH_CONTEXT%SCATTER_LW',1,ZHOOK_HANDLE)
END SUBROUTINE SCATTER_LW

SUBROUTINE RELEASE_LW(YD)
  CLASS(SW_BATCH_CONTEXT_TYPE), INTENT(INOUT) :: YD
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('SW_BATCH_CONTEXT%RELEASE_LW',0,ZHOOK_HANDLE)
  IF (YD%LW_ENABLED) THEN
    !$ACC WAIT(1)
    !$ACC EXIT DATA DELETE(YD%LW_SEED,YD%LW_CLOUD,YD%LW_OVERLAP,YD%LW_OPT,YD%LW_COPT,YD%LW_UNUSED)
    !$ACC EXIT DATA DELETE(YD%LW_PLANCK,YD%LW_BOUNDARY,YD%LW_COVER,YD%LW_SURFACE,YD%LW_FLUX,YD%LW_DERIV)
    DEALLOCATE(YD%LW_STAGED,YD%LW_SEED,YD%LW_CLOUD,YD%LW_OVERLAP,YD%LW_OPT,YD%LW_COPT,YD%LW_UNUSED)
    DEALLOCATE(YD%LW_PLANCK,YD%LW_BOUNDARY,YD%LW_COVER,YD%LW_SURFACE,YD%LW_FLUX,YD%LW_DERIV)
  ENDIF
  YD%LW_ENABLED=.FALSE.
  IF (LHOOK) CALL DR_HOOK('SW_BATCH_CONTEXT%RELEASE_LW',1,ZHOOK_HANDLE)
END SUBROUTINE RELEASE_LW
