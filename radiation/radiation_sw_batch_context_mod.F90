MODULE RADIATION_SW_BATCH_CONTEXT_MOD
  USE PARKIND1, ONLY : JPIM,JPRB
  USE YOMHOOK, ONLY : LHOOK,DR_HOOK,JPHOOK
  USE RADIATION_CONFIG, ONLY : CONFIG_TYPE,ISOLVERMCICAACC
  USE RADIATION_SINGLE_LEVEL, ONLY : SINGLE_LEVEL_TYPE
  USE RADIATION_THERMODYNAMICS, ONLY : THERMODYNAMICS_TYPE
  USE RADIATION_GAS, ONLY : GAS_TYPE
  USE RADIATION_CLOUD, ONLY : CLOUD_TYPE
  USE RADIATION_AEROSOL, ONLY : AEROSOL_TYPE
  USE RADIATION_FLUX, ONLY : FLUX_TYPE
  USE RADIATION_MCICA_SW_BATCH_MOD, ONLY : SW_BATCH_WORKSPACE_TYPE,SOLVE_SW_BATCH
  IMPLICIT NONE
  PRIVATE
  PUBLIC :: SW_BATCH_CONTEXT_TYPE,RADIATION_BLOCK_STATE_TYPE
  TYPE RADIATION_BLOCK_STATE_TYPE
    TYPE(SINGLE_LEVEL_TYPE) :: SINGLE_LEVEL
    TYPE(THERMODYNAMICS_TYPE) :: THERMODYNAMICS
    TYPE(GAS_TYPE) :: GAS
    TYPE(CLOUD_TYPE) :: CLOUD
    TYPE(AEROSOL_TYPE) :: AEROSOL
    TYPE(FLUX_TYPE) :: FLUX
    LOGICAL :: PREPARED=.FALSE.
  END TYPE RADIATION_BLOCK_STATE_TYPE
  TYPE SW_BATCH_CONTEXT_TYPE
    INTEGER(KIND=JPIM) :: NLEV=0,NCOL=0,NG=0,NBAND=0,CAPACITY=0,ACTIVE=0
    LOGICAL :: SOLVED=.FALSE.
    LOGICAL, ALLOCATABLE :: STAGED(:)
    INTEGER(KIND=JPIM), ALLOCATABLE :: FIRST(:),LAST(:),SEED(:,:)
    REAL(KIND=JPRB), ALLOCATABLE :: MU(:,:),CLOUD(:,:,:,:),OVERLAP(:,:,:)
    REAL(KIND=JPRB), ALLOCATABLE :: OPT(:,:,:,:,:),COPT(:,:,:,:,:),BOUNDARY(:,:,:,:)
    REAL(KIND=JPRB), ALLOCATABLE :: COVER(:,:),SURFACE(:,:,:,:),FLUX(:,:,:,:)
    TYPE(SW_BATCH_WORKSPACE_TYPE) :: WORK
  CONTAINS
    PROCEDURE :: INIT
    PROCEDURE :: BEGIN_TILE
    PROCEDURE :: STAGE
    PROCEDURE :: SOLVE
    PROCEDURE :: SCATTER
    PROCEDURE :: RELEASE
  END TYPE SW_BATCH_CONTEXT_TYPE
#include "abor1.intfb.h"
CONTAINS
SUBROUTINE INIT(YD,KCOL,KLEV,KCAP,YDCONFIG)
  CLASS(SW_BATCH_CONTEXT_TYPE), INTENT(INOUT) :: YD
  INTEGER(KIND=JPIM), INTENT(IN) :: KCOL,KLEV,KCAP
  TYPE(CONFIG_TYPE), INTENT(IN) :: YDCONFIG
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('SW_BATCH_CONTEXT%INIT',0,ZHOOK_HANDLE)
  IF (.NOT. YDCONFIG%DO_SW .OR. .NOT. YDCONFIG%DO_CLEAR .OR. .NOT. YDCONFIG%DO_SW_DIRECT &
    & .OR. YDCONFIG%DO_SW_DELTA_SCALING_WITH_GASES .OR. YDCONFIG%I_SOLVER_SW /= ISOLVERMCICAACC) &
    & CALL ABOR1('SW batch context: unsupported configuration')
  CALL YD%RELEASE()
  YD%NCOL=KCOL
  YD%NLEV=KLEV
  YD%CAPACITY=KCAP
  YD%NG=YDCONFIG%N_G_SW
  YD%NBAND=YDCONFIG%N_BANDS_SW
  ALLOCATE(YD%STAGED(KCAP),YD%FIRST(KCAP),YD%LAST(KCAP),YD%SEED(KCOL,KCAP),YD%MU(KCOL,KCAP))
  ALLOCATE(YD%CLOUD(KCOL,KLEV,KCAP,2),YD%OVERLAP(KCOL,KLEV-1,KCAP))
  ALLOCATE(YD%OPT(YD%NG,KLEV,KCOL,KCAP,3),YD%COPT(YD%NBAND,KLEV,KCOL,KCAP,3))
  ALLOCATE(YD%BOUNDARY(YD%NG,KCOL,KCAP,3),YD%COVER(KCOL,KCAP),YD%SURFACE(YD%NG,KCOL,KCAP,4))
  ALLOCATE(YD%FLUX(KCOL,KLEV+1,KCAP,6))
  !$ACC ENTER DATA COPYIN(YD)
  !$ACC ENTER DATA CREATE(YD%FIRST,YD%LAST,YD%SEED,YD%MU,YD%CLOUD,YD%OVERLAP)
  !$ACC ENTER DATA CREATE(YD%OPT,YD%COPT,YD%BOUNDARY,YD%COVER,YD%SURFACE,YD%FLUX)
  CALL YD%WORK%INIT(KLEV,KCOL,KCAP,YD%NG,1)
  IF (LHOOK) CALL DR_HOOK('SW_BATCH_CONTEXT%INIT',1,ZHOOK_HANDLE)
END SUBROUTINE INIT

SUBROUTINE BEGIN_TILE(YD,KACTIVE)
  CLASS(SW_BATCH_CONTEXT_TYPE), INTENT(INOUT) :: YD
  INTEGER(KIND=JPIM), INTENT(IN) :: KACTIVE
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('SW_BATCH_CONTEXT%BEGIN_TILE',0,ZHOOK_HANDLE)
  IF (KACTIVE < 1 .OR. KACTIVE > YD%CAPACITY) CALL ABOR1('SW batch context: invalid active count')
  YD%ACTIVE=KACTIVE
  YD%STAGED(:)=.FALSE.
  YD%SOLVED=.FALSE.
  IF (LHOOK) CALL DR_HOOK('SW_BATCH_CONTEXT%BEGIN_TILE',1,ZHOOK_HANDLE)
END SUBROUTINE BEGIN_TILE

SUBROUTINE STAGE(YD,KSLOT,KFIRST,KLAST,YDSINGLE,YDCLOUD,POD,PSSA,PG,PODCL,PSSACL,PGCL,PALBD,PALBF,PIN)
  CLASS(SW_BATCH_CONTEXT_TYPE), INTENT(INOUT) :: YD
  INTEGER(KIND=JPIM), INTENT(IN) :: KSLOT,KFIRST,KLAST
  TYPE(SINGLE_LEVEL_TYPE), INTENT(IN) :: YDSINGLE
  TYPE(CLOUD_TYPE), INTENT(IN) :: YDCLOUD
  REAL(KIND=JPRB), INTENT(IN) :: POD(YD%NG,YD%NLEV,KFIRST:KLAST),PSSA(YD%NG,YD%NLEV,KFIRST:KLAST)
  REAL(KIND=JPRB), INTENT(IN) :: PG(YD%NG,YD%NLEV,KFIRST:KLAST)
  REAL(KIND=JPRB), INTENT(IN) :: PODCL(YD%NBAND,YD%NLEV,KFIRST:KLAST),PSSACL(YD%NBAND,YD%NLEV,KFIRST:KLAST)
  REAL(KIND=JPRB), INTENT(IN) :: PGCL(YD%NBAND,YD%NLEV,KFIRST:KLAST)
  REAL(KIND=JPRB), INTENT(IN) :: PALBD(YD%NG,KFIRST:KLAST),PALBF(YD%NG,KFIRST:KLAST),PIN(YD%NG,KFIRST:KLAST)
  INTEGER(KIND=JPIM) :: JL,JK,JG
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('SW_BATCH_CONTEXT%STAGE',0,ZHOOK_HANDLE)
  IF (KSLOT < 1 .OR. KSLOT > YD%ACTIVE) CALL ABOR1('SW batch context: invalid slot')
  IF (YD%STAGED(KSLOT) .OR. YD%SOLVED) CALL ABOR1('SW batch context: stage out of order')
  YD%FIRST(KSLOT)=KFIRST
  YD%LAST(KSLOT)=KLAST
  !$ACC UPDATE DEVICE(YD%FIRST(KSLOT:KSLOT),YD%LAST(KSLOT:KSLOT)) ASYNC(1)
  !$ACC PARALLEL LOOP COLLAPSE(2) GANG VECTOR DEFAULT(PRESENT) ASYNC(1)
  DO JK=1,YD%NLEV
    DO JL=KFIRST,KLAST
      YD%CLOUD(JL,JK,KSLOT,1)=YDCLOUD%FRACTION(JL,JK)
      YD%CLOUD(JL,JK,KSLOT,2)=YDCLOUD%FRACTIONAL_STD(JL,JK)
      IF (JK < YD%NLEV) YD%OVERLAP(JL,JK,KSLOT)=YDCLOUD%OVERLAP_PARAM(JL,JK)
      IF (JK == 1) THEN
        YD%SEED(JL,KSLOT)=YDSINGLE%ISEED(JL)
        YD%MU(JL,KSLOT)=YDSINGLE%COS_SZA(JL)
      ENDIF
    ENDDO
  ENDDO
  !$ACC PARALLEL LOOP COLLAPSE(3) GANG VECTOR DEFAULT(PRESENT) ASYNC(1)
  DO JL=KFIRST,KLAST
    DO JK=1,YD%NLEV
      DO JG=1,YD%NG
        YD%OPT(JG,JK,JL,KSLOT,1)=POD(JG,JK,JL)
        YD%OPT(JG,JK,JL,KSLOT,2)=PSSA(JG,JK,JL)
        YD%OPT(JG,JK,JL,KSLOT,3)=PG(JG,JK,JL)
        IF (JK == 1) THEN
          YD%BOUNDARY(JG,JL,KSLOT,1)=PALBD(JG,JL)
          YD%BOUNDARY(JG,JL,KSLOT,2)=PALBF(JG,JL)
          YD%BOUNDARY(JG,JL,KSLOT,3)=PIN(JG,JL)
        ENDIF
      ENDDO
    ENDDO
  ENDDO
  !$ACC PARALLEL LOOP COLLAPSE(3) GANG VECTOR DEFAULT(PRESENT) ASYNC(1)
  DO JL=KFIRST,KLAST
    DO JK=1,YD%NLEV
      DO JG=1,YD%NBAND
        YD%COPT(JG,JK,JL,KSLOT,1)=PODCL(JG,JK,JL)
        YD%COPT(JG,JK,JL,KSLOT,2)=PSSACL(JG,JK,JL)
        YD%COPT(JG,JK,JL,KSLOT,3)=PGCL(JG,JK,JL)
      ENDDO
    ENDDO
  ENDDO
  YD%STAGED(KSLOT)=.TRUE.
  IF (LHOOK) CALL DR_HOOK('SW_BATCH_CONTEXT%STAGE',1,ZHOOK_HANDLE)
END SUBROUTINE STAGE

SUBROUTINE SOLVE(YD,YDCONFIG)
  CLASS(SW_BATCH_CONTEXT_TYPE), INTENT(INOUT) :: YD
  TYPE(CONFIG_TYPE), INTENT(IN) :: YDCONFIG
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('SW_BATCH_CONTEXT%SOLVE',0,ZHOOK_HANDLE)
  IF (YD%ACTIVE < 1 .OR. YD%SOLVED) CALL ABOR1('SW batch context: solve out of order')
  IF (.NOT. ALL(YD%STAGED(1:YD%ACTIVE))) CALL ABOR1('SW batch context: missing slot')
  CALL SOLVE_SW_BATCH(YD%WORK,YDCONFIG,YD%ACTIVE,YD%FIRST,YD%LAST,YD%SEED,YD%MU, &
    & YD%CLOUD(:,:,:,1),YD%CLOUD(:,:,:,2),YD%OVERLAP,YD%OPT(:,:,:,:,1),YD%OPT(:,:,:,:,2),YD%OPT(:,:,:,:,3), &
    & YD%COPT(:,:,:,:,1),YD%COPT(:,:,:,:,2),YD%COPT(:,:,:,:,3), &
    & YD%BOUNDARY(:,:,:,1),YD%BOUNDARY(:,:,:,2),YD%BOUNDARY(:,:,:,3),YD%COVER,YD%SURFACE,YD%FLUX)
  YD%SOLVED=.TRUE.
  IF (LHOOK) CALL DR_HOOK('SW_BATCH_CONTEXT%SOLVE',1,ZHOOK_HANDLE)
END SUBROUTINE SOLVE

SUBROUTINE SCATTER(YD,KSLOT,YDFLUX)
  CLASS(SW_BATCH_CONTEXT_TYPE), INTENT(INOUT) :: YD
  INTEGER(KIND=JPIM), INTENT(IN) :: KSLOT
  TYPE(FLUX_TYPE), INTENT(INOUT) :: YDFLUX
  INTEGER(KIND=JPIM) :: JL,JK,JG
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('SW_BATCH_CONTEXT%SCATTER',0,ZHOOK_HANDLE)
  IF (.NOT. YD%SOLVED) CALL ABOR1('SW batch context: scatter before solve')
  !$ACC PARALLEL LOOP COLLAPSE(2) GANG VECTOR DEFAULT(PRESENT) ASYNC(1)
  DO JK=1,YD%NLEV+1
    DO JL=YD%FIRST(KSLOT),YD%LAST(KSLOT)
      YDFLUX%SW_UP_CLEAR(JL,JK)=YD%FLUX(JL,JK,KSLOT,1)
      YDFLUX%SW_DN_CLEAR(JL,JK)=YD%FLUX(JL,JK,KSLOT,2)
      YDFLUX%SW_UP(JL,JK)=YD%FLUX(JL,JK,KSLOT,3)
      YDFLUX%SW_DN(JL,JK)=YD%FLUX(JL,JK,KSLOT,4)
      YDFLUX%SW_DN_DIRECT(JL,JK)=YD%FLUX(JL,JK,KSLOT,5)
      YDFLUX%SW_DN_DIRECT_CLEAR(JL,JK)=YD%FLUX(JL,JK,KSLOT,6)
      IF (JK == 1) YDFLUX%CLOUD_COVER_SW(JL)=YD%COVER(JL,KSLOT)
    ENDDO
  ENDDO
  !$ACC PARALLEL LOOP COLLAPSE(2) GANG VECTOR DEFAULT(PRESENT) ASYNC(1)
  DO JL=YD%FIRST(KSLOT),YD%LAST(KSLOT)
    DO JG=1,YD%NG
      YDFLUX%SW_DN_DIFFUSE_SURF_CLEAR_G(JG,JL)=YD%SURFACE(JG,JL,KSLOT,1)
      YDFLUX%SW_DN_DIRECT_SURF_CLEAR_G(JG,JL)=YD%SURFACE(JG,JL,KSLOT,2)
      YDFLUX%SW_DN_DIFFUSE_SURF_G(JG,JL)=YD%SURFACE(JG,JL,KSLOT,3)
      YDFLUX%SW_DN_DIRECT_SURF_G(JG,JL)=YD%SURFACE(JG,JL,KSLOT,4)
    ENDDO
  ENDDO
  IF (LHOOK) CALL DR_HOOK('SW_BATCH_CONTEXT%SCATTER',1,ZHOOK_HANDLE)
END SUBROUTINE SCATTER

SUBROUTINE RELEASE(YD)
  CLASS(SW_BATCH_CONTEXT_TYPE), INTENT(INOUT) :: YD
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('SW_BATCH_CONTEXT%RELEASE',0,ZHOOK_HANDLE)
  IF (ALLOCATED(YD%OPT)) THEN
    !$ACC WAIT(1)
    !$ACC EXIT DATA DELETE(YD%FIRST,YD%LAST,YD%SEED,YD%MU,YD%CLOUD,YD%OVERLAP)
    !$ACC EXIT DATA DELETE(YD%OPT,YD%COPT,YD%BOUNDARY,YD%COVER,YD%SURFACE,YD%FLUX)
    !$ACC EXIT DATA DELETE(YD)
    DEALLOCATE(YD%STAGED,YD%FIRST,YD%LAST,YD%SEED,YD%MU,YD%CLOUD,YD%OVERLAP)
    DEALLOCATE(YD%OPT,YD%COPT,YD%BOUNDARY,YD%COVER,YD%SURFACE,YD%FLUX)
  ENDIF
  CALL YD%WORK%RELEASE()
  YD%ACTIVE=0
  IF (LHOOK) CALL DR_HOOK('SW_BATCH_CONTEXT%RELEASE',1,ZHOOK_HANDLE)
END SUBROUTINE RELEASE
END MODULE RADIATION_SW_BATCH_CONTEXT_MOD
