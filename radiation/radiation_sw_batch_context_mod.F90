    & YDCONFIG%PDF_SAMPLER%NCDF,YDCONFIG%PDF_SAMPLER%NFSD,0,YD%LW_NBAND,YD%LW_NBAND, &
    & YDCONFIG%USE_BETA_OVERLAP,.TRUE.,YD%LW_DERIVATIVES,YDCONFIG%CLOUD_FRACTION_THRESHOLD, &
    & YDCONFIG%CLOUD_INHOM_DECORR_SCALING,YDCONFIG%PDF_SAMPLER%FSD1,YDCONFIG%PDF_SAMPLER%INV_FSD_INTERVAL, &
