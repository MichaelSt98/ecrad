! Experimental block-aware SW McICA. Numerical algorithms are taken from
! radiation_mcica_acc_gpoint_sw and cloud_generator_block_acc_gpoint.
! Host ownership is separate from the explicit-shape computational core.
MODULE RADIATION_MCICA_SW_BATCH_MOD
  USE PARKIND1, ONLY : JPIM, JPRB
  USE YOMHOOK, ONLY : LHOOK, DR_HOOK, JPHOOK
  IMPLICIT NONE
  PRIVATE
  PUBLIC :: SW_BATCH_WORKSPACE_TYPE, SOLVE_SW_BATCH
#include "abor1.intfb.h"

  ! Surface channels: clear diffuse/direct, total diffuse/direct.
  ! Broadband channels: clear up/down, total up/down, total/clear direct.
  TYPE SW_BATCH_WORKSPACE_TYPE
    PRIVATE
    INTEGER(KIND=JPIM) :: NLEV=0, NCOL=0, NBLOCK=0, NG=0, QUEUE=1
    REAL(KIND=JPRB), ALLOCATABLE :: FRAC(:,:,:), FSD(:,:,:), OVERLAP(:,:,:)
    REAL(KIND=JPRB), ALLOCATABLE :: CUM(:,:,:), PAIR(:,:,:), SCALING(:,:,:,:)
    REAL(KIND=JPRB), ALLOCATABLE :: PRODUCT(:,:)
    REAL(KIND=JPRB), ALLOCATABLE :: WORK(:,:,:,:,:)
    INTEGER(KIND=JPIM), ALLOCATABLE :: FIRST(:,:), LAST(:,:)
  CONTAINS
    PROCEDURE :: INIT => INIT_SW_BATCH
    PROCEDURE :: RELEASE => RELEASE_SW_BATCH
  END TYPE SW_BATCH_WORKSPACE_TYPE

CONTAINS

SUBROUTINE INIT_SW_BATCH(YDWORK, KLEV, KCOL, KBLOCK, KG, KQUEUE)
  CLASS(SW_BATCH_WORKSPACE_TYPE), INTENT(INOUT) :: YDWORK
  INTEGER(KIND=JPIM), INTENT(IN) :: KLEV, KCOL, KBLOCK, KG, KQUEUE
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('INIT_SW_BATCH',0,ZHOOK_HANDLE)
  IF (KLEV < 2 .OR. MIN(KCOL,KBLOCK,KG) < 1 .OR. KQUEUE < 0) &
    & CALL ABOR1('INIT_SW_BATCH: pilot requires at least two levels and positive extents')
  IF (YDWORK%NLEV /= KLEV .OR. YDWORK%NCOL /= KCOL .OR. YDWORK%NBLOCK /= KBLOCK &
    & .OR. YDWORK%NG /= KG .OR. YDWORK%QUEUE /= KQUEUE) THEN
    CALL YDWORK%RELEASE()
    YDWORK%NLEV=KLEV
    YDWORK%NCOL=KCOL
    YDWORK%NBLOCK=KBLOCK
    YDWORK%NG=KG
    YDWORK%QUEUE=KQUEUE
    ALLOCATE(YDWORK%FRAC(KLEV,KCOL,KBLOCK), YDWORK%FSD(KLEV,KCOL,KBLOCK))
    ALLOCATE(YDWORK%OVERLAP(KLEV-1,KCOL,KBLOCK), YDWORK%PAIR(KLEV-1,KCOL,KBLOCK))
    ALLOCATE(YDWORK%CUM(KLEV,KCOL,KBLOCK), YDWORK%SCALING(KG,KLEV,KCOL,KBLOCK))
    ALLOCATE(YDWORK%WORK(KG,KLEV+1,KCOL,KBLOCK,7))
    ALLOCATE(YDWORK%FIRST(KCOL,KBLOCK), YDWORK%LAST(KCOL,KBLOCK))
    ALLOCATE(YDWORK%PRODUCT(KCOL,KBLOCK))
    !$ACC ENTER DATA COPYIN(YDWORK)
    !$ACC ENTER DATA CREATE(YDWORK%FRAC,YDWORK%FSD,YDWORK%OVERLAP,YDWORK%PAIR,YDWORK%CUM)
    !$ACC ENTER DATA CREATE(YDWORK%SCALING,YDWORK%WORK,YDWORK%FIRST,YDWORK%LAST)
    !$ACC ENTER DATA CREATE(YDWORK%PRODUCT)
  ENDIF
  IF (LHOOK) CALL DR_HOOK('INIT_SW_BATCH',1,ZHOOK_HANDLE)
END SUBROUTINE INIT_SW_BATCH

SUBROUTINE RELEASE_SW_BATCH(YDWORK)
  CLASS(SW_BATCH_WORKSPACE_TYPE), INTENT(INOUT) :: YDWORK
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('RELEASE_SW_BATCH',0,ZHOOK_HANDLE)
  IF (ALLOCATED(YDWORK%WORK)) THEN
    !$ACC WAIT(YDWORK%QUEUE)
    !$ACC EXIT DATA DELETE(YDWORK%FRAC,YDWORK%FSD,YDWORK%OVERLAP,YDWORK%PAIR,YDWORK%CUM)
    !$ACC EXIT DATA DELETE(YDWORK%SCALING,YDWORK%WORK,YDWORK%FIRST,YDWORK%LAST)
    !$ACC EXIT DATA DELETE(YDWORK%PRODUCT)
    !$ACC EXIT DATA DELETE(YDWORK)
    DEALLOCATE(YDWORK%FRAC,YDWORK%FSD,YDWORK%OVERLAP,YDWORK%PAIR,YDWORK%CUM)
    DEALLOCATE(YDWORK%SCALING,YDWORK%WORK,YDWORK%FIRST,YDWORK%LAST)
    DEALLOCATE(YDWORK%PRODUCT)
  ENDIF
  YDWORK%NLEV=0
  YDWORK%NCOL=0
  YDWORK%NBLOCK=0
  YDWORK%NG=0
  IF (LHOOK) CALL DR_HOOK('RELEASE_SW_BATCH',1,ZHOOK_HANDLE)
END SUBROUTINE RELEASE_SW_BATCH

SUBROUTINE SOLVE_SW_BATCH(YDWORK, YDCONFIG, KACTIVE, KFIRST, KLAST, KSEED, PMU, &
  & PCLOUD, PFSD, POVERLAP, POD, PSSA, PG, PODCL, PSSACL, PGCL, &
  & PALBD, PALBF, PINCOMING, PCOVER, PSURFACE, PFLUX)
  USE RADIATION_CONFIG, ONLY : CONFIG_TYPE
  CLASS(SW_BATCH_WORKSPACE_TYPE), INTENT(INOUT) :: YDWORK
  TYPE(CONFIG_TYPE), INTENT(IN) :: YDCONFIG
  INTEGER(KIND=JPIM), INTENT(IN) :: KACTIVE
  INTEGER(KIND=JPIM), INTENT(IN) :: KFIRST(YDWORK%NBLOCK), KLAST(YDWORK%NBLOCK)
  INTEGER(KIND=JPIM), INTENT(IN) :: KSEED(YDWORK%NCOL,YDWORK%NBLOCK)
  REAL(KIND=JPRB), INTENT(IN) :: PMU(YDWORK%NCOL,YDWORK%NBLOCK)
  REAL(KIND=JPRB), INTENT(IN) :: PCLOUD(YDWORK%NCOL,YDWORK%NLEV,YDWORK%NBLOCK)
  REAL(KIND=JPRB), INTENT(IN) :: PFSD(YDWORK%NCOL,YDWORK%NLEV,YDWORK%NBLOCK)
  REAL(KIND=JPRB), INTENT(IN) :: POVERLAP(YDWORK%NCOL,YDWORK%NLEV-1,YDWORK%NBLOCK)
  REAL(KIND=JPRB), INTENT(IN) :: POD(YDWORK%NG,YDWORK%NLEV,YDWORK%NCOL,YDWORK%NBLOCK)
  REAL(KIND=JPRB), INTENT(IN) :: PSSA(YDWORK%NG,YDWORK%NLEV,YDWORK%NCOL,YDWORK%NBLOCK)
  REAL(KIND=JPRB), INTENT(IN) :: PG(YDWORK%NG,YDWORK%NLEV,YDWORK%NCOL,YDWORK%NBLOCK)
  REAL(KIND=JPRB), INTENT(IN) :: PODCL(YDCONFIG%N_BANDS_SW,YDWORK%NLEV,YDWORK%NCOL,YDWORK%NBLOCK)
  REAL(KIND=JPRB), INTENT(IN) :: PSSACL(YDCONFIG%N_BANDS_SW,YDWORK%NLEV,YDWORK%NCOL,YDWORK%NBLOCK)
  REAL(KIND=JPRB), INTENT(IN) :: PGCL(YDCONFIG%N_BANDS_SW,YDWORK%NLEV,YDWORK%NCOL,YDWORK%NBLOCK)
  REAL(KIND=JPRB), INTENT(IN) :: PALBD(YDWORK%NG,YDWORK%NCOL,YDWORK%NBLOCK)
  REAL(KIND=JPRB), INTENT(IN) :: PALBF(YDWORK%NG,YDWORK%NCOL,YDWORK%NBLOCK)
  REAL(KIND=JPRB), INTENT(IN) :: PINCOMING(YDWORK%NG,YDWORK%NCOL,YDWORK%NBLOCK)
  REAL(KIND=JPRB), INTENT(INOUT) :: PCOVER(YDWORK%NCOL,YDWORK%NBLOCK)
  REAL(KIND=JPRB), INTENT(INOUT) :: PSURFACE(YDWORK%NG,YDWORK%NCOL,YDWORK%NBLOCK,4)
  REAL(KIND=JPRB), INTENT(INOUT) :: PFLUX(YDWORK%NCOL,YDWORK%NLEV+1,YDWORK%NBLOCK,6)
  INTEGER(KIND=JPIM) :: JB
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('SOLVE_SW_BATCH',0,ZHOOK_HANDLE)
  IF (.NOT. ALLOCATED(YDWORK%WORK)) CALL ABOR1('SOLVE_SW_BATCH: initialise workspace first')
  IF (.NOT. YDCONFIG%DO_CLEAR .OR. YDCONFIG%DO_SW_DELTA_SCALING_WITH_GASES) &
    & CALL ABOR1('SOLVE_SW_BATCH: pilot requires clear diagnostics and pre-scaled aerosol optics')
  IF (YDCONFIG%N_G_SW /= YDWORK%NG) CALL ABOR1('SOLVE_SW_BATCH: incompatible spectral shape')
  IF (YDCONFIG%CLOUD_FRACTION_THRESHOLD <= 0.0_JPRB .OR. YDCONFIG%CLOUD_INHOM_DECORR_SCALING <= 0.0_JPRB) &
    & CALL ABOR1('SOLVE_SW_BATCH: threshold and decorrelation scaling must be positive')
  IF (YDCONFIG%PDF_SAMPLER%NCDF < 2 .OR. YDCONFIG%PDF_SAMPLER%NFSD < 2) &
    & CALL ABOR1('SOLVE_SW_BATCH: PDF table needs at least two points per dimension')
  IF (KACTIVE < 0 .OR. KACTIVE > YDWORK%NBLOCK) CALL ABOR1('SOLVE_SW_BATCH: invalid active blocks')
  DO JB=1,KACTIVE
    ! An empty block is represented by FIRST=1, LAST=0.
    IF (KFIRST(JB) < 1 .OR. KFIRST(JB) > YDWORK%NCOL+1 .OR. KLAST(JB) < 0 &
      & .OR. KLAST(JB) > YDWORK%NCOL .OR. KLAST(JB) < KFIRST(JB)-1) &
      & CALL ABOR1('SOLVE_SW_BATCH: invalid column bounds')
  ENDDO
  IF (KACTIVE > 0) CALL SW_BATCH_CORE(YDWORK%NLEV,YDWORK%NCOL,YDWORK%NBLOCK,KACTIVE,KFIRST,KLAST, &
    & YDWORK%NG,YDCONFIG%N_BANDS_SW,YDCONFIG%PDF_SAMPLER%NCDF,YDCONFIG%PDF_SAMPLER%NFSD, &
    & YDWORK%QUEUE,YDCONFIG%USE_BETA_OVERLAP,YDCONFIG%CLOUD_FRACTION_THRESHOLD, &
    & YDCONFIG%CLOUD_INHOM_DECORR_SCALING,YDCONFIG%PDF_SAMPLER%FSD1, &
    & YDCONFIG%PDF_SAMPLER%INV_FSD_INTERVAL,YDCONFIG%I_BAND_FROM_REORDERED_G_SW, &
    & YDCONFIG%PDF_SAMPLER%VAL,KSEED,PMU,PCLOUD,PFSD,POVERLAP,POD,PSSA,PG,PODCL,PSSACL,PGCL, &
    & PALBD,PALBF,PINCOMING,YDWORK%FRAC,YDWORK%FSD,YDWORK%OVERLAP,YDWORK%CUM,YDWORK%PAIR, &
    & YDWORK%PRODUCT,YDWORK%FIRST,YDWORK%LAST,YDWORK%SCALING,YDWORK%WORK,PCOVER,PSURFACE,PFLUX)
  ! Asynchronous: caller owns inputs/outputs until this workspace queue completes.
  IF (LHOOK) CALL DR_HOOK('SOLVE_SW_BATCH',1,ZHOOK_HANDLE)
END SUBROUTINE SOLVE_SW_BATCH

SUBROUTINE SW_BATCH_CORE(KLEV,KCOL,KBLOCK,KACTIVE,KFIRST,KLAST,KG,KBAND,KNCDF,KNFSD, &
  & KQUEUE,LDBETA,PTHRESH,PDECOR,PFSD1,PINVFSD,KMAP,PPDF,KSEED,PMU,PCLOUD,PFSD,POVERLAP, &
  & POD,PSSA,PG,PODCL,PSSACL,PGCL,PALBD,PALBF,PINCOMING,PFRAC,PFRASTD,POVER,PCUM,PPAIR, &
  & PPRODUCT,KBEGIN,KEND,PSCALE,PWORK,PCOVER,PSURFACE,PFLUX)
  USE PARKIND1, ONLY : JPIB
  USE RADIATION_CLOUD_COVER, ONLY : BETA2ALPHA, MAXCLOUDFRAC
  USE RADIATION_RANDOM_NUMBERS, ONLY : IMINSTDA0, IMINSTDA, IMINSTDM, UNIFORM_DISTRIBUTION_ACC_GPOINT
  USE RADIATION_ADDING_ICA_SW, ONLY : ADDING_ICA_SW_RECOMPUTE_ACC_GPOINT, &
    & ADDING_ICA_SW_RECOMPUTE_TOTAL_ACC_GPOINT
  INTEGER(KIND=JPIM), INTENT(IN) :: KLEV,KCOL,KBLOCK,KACTIVE
  INTEGER(KIND=JPIM), INTENT(IN) :: KFIRST(KBLOCK),KLAST(KBLOCK)
  INTEGER(KIND=JPIM), INTENT(IN) :: KG,KBAND,KNCDF,KNFSD,KQUEUE
  LOGICAL, INTENT(IN) :: LDBETA
  REAL(KIND=JPRB), INTENT(IN) :: PTHRESH,PDECOR,PFSD1,PINVFSD
  INTEGER(KIND=JPIM), INTENT(IN) :: KMAP(KG)
  REAL(KIND=JPRB), INTENT(IN) :: PPDF(KNCDF,KNFSD)
  INTEGER(KIND=JPIM), INTENT(IN) :: KSEED(KCOL,KBLOCK)
  REAL(KIND=JPRB), INTENT(IN) :: PMU(KCOL,KBLOCK),PCLOUD(KCOL,KLEV,KBLOCK),PFSD(KCOL,KLEV,KBLOCK)
  REAL(KIND=JPRB), INTENT(IN) :: POVERLAP(KCOL,KLEV-1,KBLOCK)
  REAL(KIND=JPRB), INTENT(IN) :: POD(KG,KLEV,KCOL,KBLOCK),PSSA(KG,KLEV,KCOL,KBLOCK),PG(KG,KLEV,KCOL,KBLOCK)
  REAL(KIND=JPRB), INTENT(IN) :: PODCL(KBAND,KLEV,KCOL,KBLOCK),PSSACL(KBAND,KLEV,KCOL,KBLOCK)
  REAL(KIND=JPRB), INTENT(IN) :: PGCL(KBAND,KLEV,KCOL,KBLOCK)
  REAL(KIND=JPRB), INTENT(IN) :: PALBD(KG,KCOL,KBLOCK),PALBF(KG,KCOL,KBLOCK),PINCOMING(KG,KCOL,KBLOCK)
  REAL(KIND=JPRB), INTENT(INOUT) :: PFRAC(KLEV,KCOL,KBLOCK),PFRASTD(KLEV,KCOL,KBLOCK)
  REAL(KIND=JPRB), INTENT(INOUT) :: POVER(KLEV-1,KCOL,KBLOCK),PCUM(KLEV,KCOL,KBLOCK),PPAIR(KLEV-1,KCOL,KBLOCK)
  REAL(KIND=JPRB), INTENT(INOUT) :: PPRODUCT(KCOL,KBLOCK)
  INTEGER(KIND=JPIM), INTENT(INOUT) :: KBEGIN(KCOL,KBLOCK),KEND(KCOL,KBLOCK)
  REAL(KIND=JPRB), INTENT(INOUT) :: PSCALE(KG,KLEV,KCOL,KBLOCK),PWORK(KG,KLEV+1,KCOL,KBLOCK,7)
  REAL(KIND=JPRB), INTENT(INOUT) :: PCOVER(KCOL,KBLOCK),PSURFACE(KG,KCOL,KBLOCK,4)
  REAL(KIND=JPRB), INTENT(INOUT) :: PFLUX(KCOL,KLEV+1,KBLOCK,6)
  INTEGER(KIND=JPIM) :: JB,JL,JK,JG,JC,ITRIGGER,INLAYERS,IFSD,ICDF,IBEGIN,IEND
  INTEGER(KIND=JPIB) :: ISTATE
  REAL(KIND=JPRB) :: ZALPHA,ZCOVER,ZMU,ZTRIGGER,ZTOP,ZCLOUD,ZINHOM1,ZINHOM2
  REAL(KIND=JPRB) :: ZOVERHANG,ZOVERINHOM,ZWFSD,ZWCDF,ZUP,ZDIFF,ZDIRECT,ZWEIGHT
  LOGICAL :: LLFILL
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('SW_BATCH_CORE',0,ZHOOK_HANDLE)

  !$ACC PARALLEL LOOP GANG VECTOR COLLAPSE(3) DEFAULT(PRESENT) ASYNC(KQUEUE) PRIVATE(ZALPHA)
  DO JB=1,KACTIVE
    DO JL=1,KCOL
      DO JK=1,KLEV
        IF (JL >= KFIRST(JB) .AND. JL <= KLAST(JB)) THEN
          PFRAC(JK,JL,JB)=PCLOUD(JL,JK,JB)
          PFRASTD(JK,JL,JB)=PFSD(JL,JK,JB)
          IF (JK < KLEV) THEN
            POVER(JK,JL,JB)=POVERLAP(JL,JK,JB)
            IF (PMU(JL,JB) > 0.0_JPRB) THEN
              ZALPHA=POVERLAP(JL,JK,JB)
              IF (LDBETA) ZALPHA=BETA2ALPHA(ZALPHA,PCLOUD(JL,JK,JB),PCLOUD(JL,JK+1,JB))
              PPAIR(JK,JL,JB)=ZALPHA*MAX(PCLOUD(JL,JK,JB),PCLOUD(JL,JK+1,JB)) &
                & +(1.0_JPRB-ZALPHA)*(PCLOUD(JL,JK,JB)+PCLOUD(JL,JK+1,JB) &
                & -PCLOUD(JL,JK,JB)*PCLOUD(JL,JK+1,JB))
            ENDIF
          ENDIF
        ENDIF
      ENDDO
    ENDDO
  ENDDO

  !$ACC PARALLEL LOOP GANG VECTOR COLLAPSE(2) DEFAULT(PRESENT) ASYNC(KQUEUE) PRIVATE(JK)
  DO JB=1,KACTIVE
    DO JL=1,KCOL
      IF (JL >= KFIRST(JB) .AND. JL <= KLAST(JB)) THEN
        KBEGIN(JL,JB)=KLEV
        KEND(JL,JB)=KLEV
        PCOVER(JL,JB)=0.0_JPRB
        IF (PMU(JL,JB) > 0.0_JPRB) THEN
          PCUM(1,JL,JB)=PFRAC(1,JL,JB)
          PPRODUCT(JL,JB)=1.0_JPRB-PFRAC(1,JL,JB)
          !$ACC LOOP SEQ
          DO JK=1,KLEV-1
            IF (PFRAC(JK,JL,JB) >= MAXCLOUDFRAC) THEN
              PPRODUCT(JL,JB)=0.0_JPRB
            ELSE
              PPRODUCT(JL,JB)=PPRODUCT(JL,JB)*(1.0_JPRB-PPAIR(JK,JL,JB))/(1.0_JPRB-PFRAC(JK,JL,JB))
            ENDIF
            PCUM(JK+1,JL,JB)=1.0_JPRB-PPRODUCT(JL,JB)
          ENDDO
          PCOVER(JL,JB)=PCUM(KLEV,JL,JB)
          IF (PCOVER(JL,JB) < PTHRESH) THEN
            PCOVER(JL,JB)=0.0_JPRB
          ELSE
            !$ACC LOOP SEQ
            DO JK=1,KLEV
              IF (PFRAC(JK,JL,JB) > 0.0_JPRB) KBEGIN(JL,JB)=MIN(JK,KBEGIN(JL,JB))
            ENDDO
            KEND(JL,JB)=KBEGIN(JL,JB)
            !$ACC LOOP SEQ
            DO JK=KBEGIN(JL,JB)+1,KLEV
              IF (PFRAC(JK,JL,JB) > 0.0_JPRB) KEND(JL,JB)=MAX(JK,KEND(JL,JB))
            ENDDO
          ENDIF
        ENDIF
      ENDIF
    ENDDO
  ENDDO

  ! Inline the validated NVIDIA generator: no sliced profile dummy on device.
  !$ACC PARALLEL LOOP GANG VECTOR COLLAPSE(3) DEFAULT(PRESENT) ASYNC(KQUEUE) VECTOR_LENGTH(32) &
  !$ACC& PRIVATE(JK,JC,ITRIGGER,INLAYERS,IFSD,ICDF,IBEGIN,IEND,ISTATE,LLFILL,ZCOVER,ZTRIGGER,ZTOP, &
  !$ACC& ZCLOUD,ZINHOM1,ZINHOM2,ZOVERHANG,ZOVERINHOM,ZWFSD,ZWCDF)
  DO JB=1,KACTIVE
    DO JL=1,KCOL
      DO JG=1,KG
        IF (JL >= KFIRST(JB) .AND. JL <= KLAST(JB)) THEN
          ZCOVER=PCOVER(JL,JB)
          IF (ZCOVER >= PTHRESH .AND. PMU(JL,JB) > 0.0_JPRB) THEN
            IBEGIN=KBEGIN(JL,JB)
            IEND=KEND(JL,JB)
            !$ACC LOOP SEQ
            DO JK=1,KLEV
              PSCALE(JG,JK,JL,JB)=0.0_JPRB
            ENDDO
            ISTATE=REAL(ABS(KSEED(JL,JB)),JPRB)
            ISTATE=NINT(MOD(ISTATE*JG*(1.0_JPRB-0.05_JPRB*JG+0.005_JPRB*JG**2)*IMINSTDA0,IMINSTDM))
            ISTATE=MOD(IMINSTDA*ISTATE,IMINSTDM)
            CALL UNIFORM_DISTRIBUTION_ACC_GPOINT(ISTATE,ZTOP)
            ZTRIGGER=ZTOP*ZCOVER
            ITRIGGER=IEND
            !$ACC LOOP SEQ
            DO JK=IBEGIN,IEND
              IF (ZTRIGGER <= PCUM(JK,JL,JB)) ITRIGGER=MIN(JK,ITRIGGER)
            ENDDO
            INLAYERS=1
            !$ACC LOOP SEQ
            DO JK=ITRIGGER+1,IEND+1
              LLFILL=.FALSE.
              IF (JK <= IEND) THEN
                CALL UNIFORM_DISTRIBUTION_ACC_GPOINT(ISTATE,ZCLOUD)
                IF (INLAYERS > 0) THEN
                  IF (ZCLOUD*PFRAC(JK-1,JL,JB) < PFRAC(JK,JL,JB)+PFRAC(JK-1,JL,JB)-PPAIR(JK-1,JL,JB)) THEN
                    INLAYERS=INLAYERS+1
                  ELSE
                    LLFILL=.TRUE.
                  ENDIF
                ELSE
                  ZOVERHANG=PCUM(JK,JL,JB)-PCUM(JK-1,JL,JB)
                  IF (ZCLOUD*(PCUM(JK-1,JL,JB)-PFRAC(JK-1,JL,JB)) &
                    & < PPAIR(JK-1,JL,JB)-ZOVERHANG-PFRAC(JK-1,JL,JB)) INLAYERS=1
                ENDIF
              ELSE
                LLFILL=.TRUE.
              ENDIF
              IF (LLFILL) THEN
                CALL UNIFORM_DISTRIBUTION_ACC_GPOINT(ISTATE,ZINHOM1)
                !$ACC LOOP SEQ
                DO JC=MAX(2,JK-INLAYERS),JK-1
                  CALL UNIFORM_DISTRIBUTION_ACC_GPOINT(ISTATE,ZINHOM2)
                  ZOVERINHOM=POVER(JC-1,JL,JB)
                  IF (IBEGIN <= JC-1 .AND. JC-1 < IEND .AND. POVER(JC-1,JL,JB) > 0.0_JPRB) &
                    & ZOVERINHOM=POVER(JC-1,JL,JB)**(1.0_JPRB/PDECOR)
                  IF (JC > JK-INLAYERS .AND. ZINHOM2 >= ZOVERINHOM) &
                    & CALL UNIFORM_DISTRIBUTION_ACC_GPOINT(ISTATE,ZINHOM1)
                  ZWCDF=ZINHOM1*(KNCDF-1)+1.0_JPRB
                  ICDF=MAX(1,MIN(INT(ZWCDF),KNCDF-1))
                  ZWCDF=MAX(0.0_JPRB,MIN(ZWCDF-ICDF,1.0_JPRB))
                  ZWFSD=(PFRASTD(JC,JL,JB)-PFSD1)*PINVFSD+1.0_JPRB
                  IFSD=MAX(1,MIN(INT(ZWFSD),KNFSD-1))
                  ZWFSD=MAX(0.0_JPRB,MIN(ZWFSD-IFSD,1.0_JPRB))
                  PSCALE(JG,JC,JL,JB)=(1.0_JPRB-ZWCDF)*(1.0_JPRB-ZWFSD)*PPDF(ICDF,IFSD) &
                    & +(1.0_JPRB-ZWCDF)*ZWFSD*PPDF(ICDF,IFSD+1) &
                    & +ZWCDF*(1.0_JPRB-ZWFSD)*PPDF(ICDF+1,IFSD)+ZWCDF*ZWFSD*PPDF(ICDF+1,IFSD+1)
                ENDDO
                INLAYERS=0
              ENDIF
            ENDDO
          ENDIF
        ENDIF
      ENDDO
    ENDDO
  ENDDO

  !$ACC PARALLEL LOOP GANG VECTOR COLLAPSE(3) DEFAULT(PRESENT) ASYNC(KQUEUE) VECTOR_LENGTH(32) PRIVATE(ZMU)
  DO JB=1,KACTIVE
    DO JL=1,KCOL
      DO JG=1,KG
        IF (JL >= KFIRST(JB) .AND. JL <= KLAST(JB)) THEN
          IF (PMU(JL,JB) > 0.0_JPRB) THEN
            ZMU=PMU(JL,JB)
            CALL ADDING_ICA_SW_RECOMPUTE_ACC_GPOINT(JG,KG,KLEV,PINCOMING(:,JL,JB), &
              & PALBF(:,JL,JB),PALBD(:,JL,JB),ZMU,POD(:,:,JL,JB),PSSA(:,:,JL,JB),PG(:,:,JL,JB), &
              & PWORK(:,:,JL,JB,1),PWORK(:,:,JL,JB,2),PWORK(:,:,JL,JB,3), &
              & PWORK(:,:,JL,JB,1),PWORK(:,:,JL,JB,2),SOURCE=PWORK(:,:,JL,JB,7))
            PSURFACE(JG,JL,JB,1)=PWORK(JG,KLEV+1,JL,JB,2)
            PSURFACE(JG,JL,JB,2)=PWORK(JG,KLEV+1,JL,JB,3)
          ELSE
            PSURFACE(JG,JL,JB,1)=0.0_JPRB
            PSURFACE(JG,JL,JB,2)=0.0_JPRB
          ENDIF
        ENDIF
      ENDDO
    ENDDO
  ENDDO

  !$ACC PARALLEL LOOP GANG VECTOR COLLAPSE(3) DEFAULT(PRESENT) ASYNC(KQUEUE) VECTOR_LENGTH(32) PRIVATE(ZMU)
  DO JB=1,KACTIVE
    DO JL=1,KCOL
      DO JG=1,KG
        IF (JL >= KFIRST(JB) .AND. JL <= KLAST(JB)) THEN
          IF (PMU(JL,JB) > 0.0_JPRB .AND. PCOVER(JL,JB) >= PTHRESH) THEN
            ZMU=PMU(JL,JB)
            CALL ADDING_ICA_SW_RECOMPUTE_TOTAL_ACC_GPOINT(JG,KG,KLEV,KMAP(JG),KBAND,KBAND, &
              & PINCOMING(:,JL,JB),PALBF(:,JL,JB),PALBD(:,JL,JB),ZMU, &
              & POD(:,:,JL,JB),PSSA(:,:,JL,JB),PG(:,:,JL,JB),PSCALE(:,:,JL,JB), &
              & PODCL(:,:,JL,JB),PSSACL(:,:,JL,JB),PGCL(:,:,JL,JB),PFRAC(:,JL,JB),PTHRESH, &
              & PWORK(:,:,JL,JB,4),PWORK(:,:,JL,JB,5),PWORK(:,:,JL,JB,6), &
              & PWORK(:,:,JL,JB,4),SOURCE=PWORK(:,:,JL,JB,7))
            PSURFACE(JG,JL,JB,3)=PCOVER(JL,JB)*PWORK(JG,KLEV+1,JL,JB,5) &
              & +(1.0_JPRB-PCOVER(JL,JB))*PSURFACE(JG,JL,JB,1)
            PSURFACE(JG,JL,JB,4)=PCOVER(JL,JB)*PWORK(JG,KLEV+1,JL,JB,6) &
              & +(1.0_JPRB-PCOVER(JL,JB))*PSURFACE(JG,JL,JB,2)
          ELSE
            PSURFACE(JG,JL,JB,3)=PSURFACE(JG,JL,JB,1)
            PSURFACE(JG,JL,JB,4)=PSURFACE(JG,JL,JB,2)
          ENDIF
        ENDIF
      ENDDO
    ENDDO
  ENDDO

  !$ACC PARALLEL LOOP GANG VECTOR COLLAPSE(3) DEFAULT(PRESENT) ASYNC(KQUEUE) &
  !$ACC& PRIVATE(JG,ZUP,ZDIFF,ZDIRECT,ZWEIGHT)
  DO JB=1,KACTIVE
    DO JL=1,KCOL
      DO JK=1,KLEV+1
        IF (JL >= KFIRST(JB) .AND. JL <= KLAST(JB)) THEN
          PFLUX(JL,JK,JB,1)=0.0_JPRB
          PFLUX(JL,JK,JB,2)=0.0_JPRB
          PFLUX(JL,JK,JB,3)=0.0_JPRB
          PFLUX(JL,JK,JB,4)=0.0_JPRB
          PFLUX(JL,JK,JB,5)=0.0_JPRB
          PFLUX(JL,JK,JB,6)=0.0_JPRB
          IF (PMU(JL,JB) > 0.0_JPRB) THEN
            ZUP=0.0_JPRB
            ZDIFF=0.0_JPRB
            ZDIRECT=0.0_JPRB
            !$ACC LOOP SEQ
            DO JG=1,KG
              ZUP=ZUP+PWORK(JG,JK,JL,JB,1)
              ZDIRECT=ZDIRECT+PWORK(JG,JK,JL,JB,3)
              ZDIFF=ZDIFF+PWORK(JG,JK,JL,JB,2)
            ENDDO
            PFLUX(JL,JK,JB,1)=ZUP
            PFLUX(JL,JK,JB,2)=ZDIFF+ZDIRECT
            PFLUX(JL,JK,JB,6)=ZDIRECT
            IF (PCOVER(JL,JB) >= PTHRESH) THEN
              ZUP=0.0_JPRB
              ZDIFF=0.0_JPRB
              ZDIRECT=0.0_JPRB
              !$ACC LOOP SEQ
              DO JG=1,KG
                ZUP=ZUP+PWORK(JG,JK,JL,JB,4)
                ZDIRECT=ZDIRECT+PWORK(JG,JK,JL,JB,6)
                ZDIFF=ZDIFF+PWORK(JG,JK,JL,JB,5)
              ENDDO
              ZWEIGHT=PCOVER(JL,JB)
              PFLUX(JL,JK,JB,3)=ZWEIGHT*ZUP+(1.0_JPRB-ZWEIGHT)*PFLUX(JL,JK,JB,1)
              PFLUX(JL,JK,JB,4)=ZWEIGHT*(ZDIFF+ZDIRECT)+(1.0_JPRB-ZWEIGHT)*PFLUX(JL,JK,JB,2)
              PFLUX(JL,JK,JB,5)=ZWEIGHT*ZDIRECT+(1.0_JPRB-ZWEIGHT)*PFLUX(JL,JK,JB,6)
            ELSE
              PFLUX(JL,JK,JB,3)=PFLUX(JL,JK,JB,1)
              PFLUX(JL,JK,JB,4)=PFLUX(JL,JK,JB,2)
              PFLUX(JL,JK,JB,5)=PFLUX(JL,JK,JB,6)
            ENDIF
          ENDIF
        ENDIF
      ENDDO
    ENDDO
  ENDDO
  IF (LHOOK) CALL DR_HOOK('SW_BATCH_CORE',1,ZHOOK_HANDLE)
END SUBROUTINE SW_BATCH_CORE

