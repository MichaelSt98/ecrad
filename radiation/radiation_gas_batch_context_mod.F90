MODULE RADIATION_GAS_BATCH_CONTEXT_MOD
  USE PARKIND1, ONLY : JPIM,JPIB,JPRB,JPRD
  USE YOMHOOK, ONLY : LHOOK,DR_HOOK,JPHOOK
  USE RADIATION_CONFIG, ONLY : CONFIG_TYPE,IGASMODELIFSRRTMG
  USE RADIATION_SINGLE_LEVEL, ONLY : SINGLE_LEVEL_TYPE
  USE RADIATION_THERMODYNAMICS, ONLY : THERMODYNAMICS_TYPE
  USE RADIATION_GAS, ONLY : GAS_TYPE
  USE RADIATION_IFS_RRTM, ONLY : GAS_OPTICS
  IMPLICIT NONE
  PRIVATE
  PUBLIC :: GAS_BATCH_CONTEXT_TYPE
  TYPE GAS_BATCH_CONTEXT_TYPE
    INTEGER(KIND=JPIM) :: NCOL=0,NLEV=0,CAPACITY=0,ACTIVE=0,NGSW=0,NGLW=0,NALB=0,NEMISS=0
    LOGICAL :: SOLVED=.FALSE.,PROFILE=.FALSE.
    REAL(KIND=JPRD) :: TIMES(3)=0.0_JPRD
    INTEGER(KIND=JPIB) :: TICKS(3)=0_JPIB
    LOGICAL, ALLOCATABLE :: STAGED(:)
    INTEGER(KIND=JPIM), ALLOCATABLE :: LAST(:)
    TYPE(SINGLE_LEVEL_TYPE) :: SINGLE
    TYPE(THERMODYNAMICS_TYPE) :: THERMO
    TYPE(GAS_TYPE) :: GAS
    REAL(KIND=JPRB), ALLOCATABLE :: OD_SW(:,:,:),SSA_SW(:,:,:),OD_LW(:,:,:),PLANCK(:,:,:)
    REAL(KIND=JPRB), ALLOCATABLE :: ALB_DIRECT(:,:),ALB_DIFFUSE(:,:),ALB_LW(:,:),EMISSION(:,:),INCOMING(:,:)
  CONTAINS
    PROCEDURE :: INIT,BEGIN_TILE,STAGE,SOLVE,LOAD,RELEASE,MARK
  END TYPE GAS_BATCH_CONTEXT_TYPE
#include "abor1.intfb.h"
CONTAINS
SUBROUTINE MARK(YD,KBUCKET,LDSTART)
  CLASS(GAS_BATCH_CONTEXT_TYPE), INTENT(INOUT) :: YD
  INTEGER(KIND=JPIM), INTENT(IN) :: KBUCKET
  LOGICAL, INTENT(IN) :: LDSTART
  INTEGER(KIND=JPIB) :: ITICK,IRATE
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('GAS_BATCH%MARK',0,ZHOOK_HANDLE)
  IF (YD%PROFILE) THEN
    !$ACC WAIT(1)
    CALL SYSTEM_CLOCK(ITICK,IRATE)
    IF (LDSTART) THEN
      YD%TICKS(KBUCKET)=ITICK
    ELSE
      YD%TIMES(KBUCKET)=YD%TIMES(KBUCKET)+REAL(ITICK-YD%TICKS(KBUCKET),JPRD)/REAL(IRATE,JPRD)
    ENDIF
  ENDIF
  IF (LHOOK) CALL DR_HOOK('GAS_BATCH%MARK',1,ZHOOK_HANDLE)
END SUBROUTINE MARK

SUBROUTINE INIT(YD,KCOL,KLEV,KCAP,KALB,KEMISS,YDCONFIG)
  CLASS(GAS_BATCH_CONTEXT_TYPE), INTENT(INOUT) :: YD
  INTEGER(KIND=JPIM), INTENT(IN) :: KCOL,KLEV,KCAP,KALB,KEMISS
  TYPE(CONFIG_TYPE), INTENT(IN) :: YDCONFIG
  INTEGER(KIND=JPIM) :: ICOL
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('GAS_BATCH%INIT',0,ZHOOK_HANDLE)
  IF (YDCONFIG%I_GAS_MODEL_SW /= IGASMODELIFSRRTMG .OR. YDCONFIG%I_GAS_MODEL_LW /= IGASMODELIFSRRTMG &
    & .OR. YDCONFIG%USE_SPECTRAL_SOLAR_SCALING) CALL ABOR1('Gas tile: unsupported gas/solar configuration')
  CALL YD%RELEASE()
  YD%NCOL=KCOL
  YD%NLEV=KLEV
  YD%CAPACITY=KCAP
  YD%NGSW=YDCONFIG%N_G_SW
  YD%NGLW=YDCONFIG%N_G_LW
  YD%NALB=KALB
  YD%NEMISS=KEMISS
  ICOL=KCOL*KCAP
  CALL YD%SINGLE%ALLOCATE(ICOL,KALB,KEMISS,USE_SW_ALBEDO_DIRECT=.TRUE.)
  CALL YD%THERMO%ALLOCATE(ICOL,KLEV)
  CALL YD%GAS%ALLOCATE(ICOL,KLEV)
  ALLOCATE(YD%STAGED(KCAP),YD%LAST(KCAP))
  ALLOCATE(YD%OD_SW(YD%NGSW,KLEV,ICOL),YD%SSA_SW(YD%NGSW,KLEV,ICOL))
  ALLOCATE(YD%OD_LW(YD%NGLW,KLEV,ICOL),YD%PLANCK(YD%NGLW,KLEV+1,ICOL))
  ALLOCATE(YD%ALB_DIRECT(YD%NGSW,ICOL),YD%ALB_DIFFUSE(YD%NGSW,ICOL),YD%INCOMING(YD%NGSW,ICOL))
  ALLOCATE(YD%ALB_LW(YD%NGLW,ICOL),YD%EMISSION(YD%NGLW,ICOL))
  !$ACC ENTER DATA COPYIN(YD)
#ifdef _OPENACC
  CALL YD%SINGLE%CREATE_DEVICE()
  CALL YD%THERMO%CREATE_DEVICE()
  CALL YD%GAS%CREATE_DEVICE()
#endif
  !$ACC ENTER DATA CREATE(YD%OD_SW,YD%SSA_SW,YD%OD_LW,YD%PLANCK)
  !$ACC ENTER DATA CREATE(YD%ALB_DIRECT,YD%ALB_DIFFUSE,YD%ALB_LW,YD%EMISSION,YD%INCOMING)
  IF (LHOOK) CALL DR_HOOK('GAS_BATCH%INIT',1,ZHOOK_HANDLE)
END SUBROUTINE INIT

SUBROUTINE BEGIN_TILE(YD,KACTIVE)
  CLASS(GAS_BATCH_CONTEXT_TYPE), INTENT(INOUT) :: YD
  INTEGER(KIND=JPIM), INTENT(IN) :: KACTIVE
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('GAS_BATCH%BEGIN_TILE',0,ZHOOK_HANDLE)
  IF (KACTIVE < 1 .OR. KACTIVE > YD%CAPACITY) CALL ABOR1('Gas tile: invalid active count')
  YD%ACTIVE=KACTIVE
  YD%STAGED(:)=.FALSE.
  YD%SOLVED=.FALSE.
  IF (LHOOK) CALL DR_HOOK('GAS_BATCH%BEGIN_TILE',1,ZHOOK_HANDLE)
END SUBROUTINE BEGIN_TILE

SUBROUTINE STAGE(YD,KSLOT,KFIRST,KLAST,YDSINGLE,YDTHERMO,YDGAS)
  CLASS(GAS_BATCH_CONTEXT_TYPE), INTENT(INOUT) :: YD
  INTEGER(KIND=JPIM), INTENT(IN) :: KSLOT,KFIRST,KLAST
  TYPE(SINGLE_LEVEL_TYPE), INTENT(IN) :: YDSINGLE
  TYPE(THERMODYNAMICS_TYPE), INTENT(IN) :: YDTHERMO
  TYPE(GAS_TYPE), INTENT(IN) :: YDGAS
  INTEGER(KIND=JPIM) :: JL,JK,JG,ICOL,IOFFSET,INGAS
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('GAS_BATCH%STAGE',0,ZHOOK_HANDLE)
  IF (YD%PROFILE) CALL YD%MARK(1,.TRUE.)
  IF (KSLOT < 1 .OR. KSLOT > YD%ACTIVE .OR. KFIRST /= 1) CALL ABOR1('Gas tile: invalid block')
  IF (YD%STAGED(KSLOT) .OR. YD%SOLVED) CALL ABOR1('Gas tile: stage out of order')
  IF (KLAST > YD%NCOL .OR. KLAST < 1) CALL ABOR1('Gas tile: invalid block length')
  IF (KSLOT < YD%ACTIVE .AND. KLAST /= YD%NCOL) CALL ABOR1('Gas tile: internal partial block')
  IF (.NOT. YDSINGLE%IS_SIMPLE_SURFACE .OR. YDTHERMO%RRTM_PASS_TEMPPRES_FL) &
    & CALL ABOR1('Gas tile: requires simple surface and half-level thermodynamics')
  IF (KSLOT == 1) THEN
    YD%GAS%IUNITS(:)=YDGAS%IUNITS(:)
    YD%GAS%SCALE_FACTOR(:)=YDGAS%SCALE_FACTOR(:)
    YD%GAS%IS_PRESENT(:)=YDGAS%IS_PRESENT(:)
    YD%GAS%IS_WELL_MIXED(:)=YDGAS%IS_WELL_MIXED(:)
    YD%GAS%ICODE(:)=YDGAS%ICODE(:)
    YD%GAS%NTYPE=YDGAS%NTYPE
    YD%SINGLE%SOLAR_IRRADIANCE=YDSINGLE%SOLAR_IRRADIANCE
    !$ACC UPDATE DEVICE(YD%GAS%IUNITS,YD%GAS%SCALE_FACTOR,YD%GAS%IS_PRESENT,YD%GAS%IS_WELL_MIXED) ASYNC(1)
    !$ACC UPDATE DEVICE(YD%GAS%ICODE,YD%GAS%NTYPE,YD%SINGLE%SOLAR_IRRADIANCE) ASYNC(1)
  ELSE
    IF (ANY(YD%GAS%IUNITS /= YDGAS%IUNITS) .OR. ANY(YD%GAS%SCALE_FACTOR /= YDGAS%SCALE_FACTOR) &
      & .OR. YD%SINGLE%SOLAR_IRRADIANCE /= YDSINGLE%SOLAR_IRRADIANCE) &
      & CALL ABOR1('Gas tile: inconsistent block metadata')
  ENDIF
  YD%LAST(KSLOT)=KLAST
  IOFFSET=(KSLOT-1)*YD%NCOL
  INGAS=SIZE(YDGAS%MIXING_RATIO,3)
  !$ACC PARALLEL LOOP COLLAPSE(2) GANG VECTOR DEFAULT(PRESENT) ASYNC(1)
  DO JK=1,YD%NLEV+1
    DO JL=KFIRST,KLAST
      ICOL=IOFFSET+JL
      YD%THERMO%PRESSURE_HL(ICOL,JK)=YDTHERMO%PRESSURE_HL(JL,JK)
      YD%THERMO%TEMPERATURE_HL(ICOL,JK)=YDTHERMO%TEMPERATURE_HL(JL,JK)
    ENDDO
  ENDDO
  !$ACC PARALLEL LOOP COLLAPSE(2) GANG VECTOR DEFAULT(PRESENT) ASYNC(1)
  DO JG=1,MAX(YD%NALB,YD%NEMISS)
    DO JL=KFIRST,KLAST
      ICOL=IOFFSET+JL
      IF (JG == 1) THEN
        YD%SINGLE%COS_SZA(ICOL)=YDSINGLE%COS_SZA(JL)
        YD%SINGLE%SKIN_TEMPERATURE(ICOL)=YDSINGLE%SKIN_TEMPERATURE(JL)
      ENDIF
      IF (JG <= YD%NALB) THEN
        YD%SINGLE%SW_ALBEDO(ICOL,JG)=YDSINGLE%SW_ALBEDO(JL,JG)
        YD%SINGLE%SW_ALBEDO_DIRECT(ICOL,JG)=YDSINGLE%SW_ALBEDO_DIRECT(JL,JG)
      ENDIF
      IF (JG <= YD%NEMISS) YD%SINGLE%LW_EMISSIVITY(ICOL,JG)=YDSINGLE%LW_EMISSIVITY(JL,JG)
    ENDDO
  ENDDO
  !$ACC PARALLEL LOOP COLLAPSE(3) GANG VECTOR DEFAULT(PRESENT) ASYNC(1)
  DO JG=1,INGAS
    DO JK=1,YD%NLEV
      DO JL=KFIRST,KLAST
        YD%GAS%MIXING_RATIO(IOFFSET+JL,JK,JG)=YDGAS%MIXING_RATIO(JL,JK,JG)
      ENDDO
    ENDDO
  ENDDO
  YD%STAGED(KSLOT)=.TRUE.
  IF (YD%PROFILE) CALL YD%MARK(1,.FALSE.)
  IF (LHOOK) CALL DR_HOOK('GAS_BATCH%STAGE',1,ZHOOK_HANDLE)
END SUBROUTINE STAGE

SUBROUTINE SOLVE(YD,YDCONFIG)
  CLASS(GAS_BATCH_CONTEXT_TYPE), INTENT(INOUT) :: YD
  TYPE(CONFIG_TYPE), INTENT(IN) :: YDCONFIG
  INTEGER(KIND=JPIM) :: IEND
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('GAS_BATCH%SOLVE',0,ZHOOK_HANDLE)
  IF (YD%PROFILE) CALL YD%MARK(2,.TRUE.)
  IF (YD%SOLVED .OR. .NOT. ALL(YD%STAGED(1:YD%ACTIVE))) CALL ABOR1('Gas tile: incomplete inputs')
  IEND=(YD%ACTIVE-1)*YD%NCOL+YD%LAST(YD%ACTIVE)
  CALL YD%SINGLE%GET_ALBEDOS(1,IEND,YDCONFIG,YD%ALB_DIRECT,YD%ALB_DIFFUSE,YD%ALB_LW)
  CALL GAS_OPTICS(YD%NCOL*YD%CAPACITY,YD%NLEV,1,IEND,YDCONFIG,YD%SINGLE,YD%THERMO,YD%GAS, &
    & YD%OD_LW,YD%OD_SW,YD%SSA_SW,LW_ALBEDO=YD%ALB_LW,PLANCK_HL=YD%PLANCK, &
    & LW_EMISSION=YD%EMISSION,INCOMING_SW=YD%INCOMING)
  YD%SOLVED=.TRUE.
  IF (YD%PROFILE) CALL YD%MARK(2,.FALSE.)
  IF (LHOOK) CALL DR_HOOK('GAS_BATCH%SOLVE',1,ZHOOK_HANDLE)
END SUBROUTINE SOLVE

SUBROUTINE LOAD(YD,KSLOT,KFIRST,KLAST,PODLW,PODSW,PSSASW,PPLANCK,PEMISSION,PALBLW,PALBD,PALBF,PIN)
  CLASS(GAS_BATCH_CONTEXT_TYPE), INTENT(INOUT) :: YD
  INTEGER(KIND=JPIM), INTENT(IN) :: KSLOT,KFIRST,KLAST
  REAL(KIND=JPRB), INTENT(OUT) :: PODLW(YD%NGLW,YD%NLEV,KFIRST:KLAST)
  REAL(KIND=JPRB), INTENT(OUT) :: PODSW(YD%NGSW,YD%NLEV,KFIRST:KLAST),PSSASW(YD%NGSW,YD%NLEV,KFIRST:KLAST)
  REAL(KIND=JPRB), INTENT(OUT) :: PPLANCK(YD%NGLW,YD%NLEV+1,KFIRST:KLAST)
  REAL(KIND=JPRB), INTENT(OUT) :: PEMISSION(YD%NGLW,KFIRST:KLAST),PALBLW(YD%NGLW,KFIRST:KLAST)
  REAL(KIND=JPRB), INTENT(OUT) :: PALBD(YD%NGSW,KFIRST:KLAST),PALBF(YD%NGSW,KFIRST:KLAST),PIN(YD%NGSW,KFIRST:KLAST)
  INTEGER(KIND=JPIM) :: JL,JK,JG,ICOL,IOFFSET
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('GAS_BATCH%LOAD',0,ZHOOK_HANDLE)
  IF (.NOT. YD%SOLVED) CALL ABOR1('Gas tile: load before solve')
  IF (YD%PROFILE) CALL YD%MARK(3,.TRUE.)
  IOFFSET=(KSLOT-1)*YD%NCOL
  !$ACC PARALLEL LOOP COLLAPSE(3) GANG VECTOR DEFAULT(PRESENT) ASYNC(1)
  DO JL=KFIRST,KLAST
    DO JK=1,YD%NLEV+1
      DO JG=1,YD%NGLW
        ICOL=IOFFSET+JL
        PPLANCK(JG,JK,JL)=YD%PLANCK(JG,JK,ICOL)
        IF (JK <= YD%NLEV) PODLW(JG,JK,JL)=YD%OD_LW(JG,JK,ICOL)
        IF (JK == 1) THEN
          PEMISSION(JG,JL)=YD%EMISSION(JG,ICOL)
          PALBLW(JG,JL)=YD%ALB_LW(JG,ICOL)
        ENDIF
      ENDDO
    ENDDO
  ENDDO
  !$ACC PARALLEL LOOP COLLAPSE(3) GANG VECTOR DEFAULT(PRESENT) ASYNC(1)
  DO JL=KFIRST,KLAST
    DO JK=1,YD%NLEV
      DO JG=1,YD%NGSW
        ICOL=IOFFSET+JL
        PODSW(JG,JK,JL)=YD%OD_SW(JG,JK,ICOL)
        PSSASW(JG,JK,JL)=YD%SSA_SW(JG,JK,ICOL)
        IF (JK == 1) THEN
          PALBD(JG,JL)=YD%ALB_DIRECT(JG,ICOL)
          PALBF(JG,JL)=YD%ALB_DIFFUSE(JG,ICOL)
          PIN(JG,JL)=YD%INCOMING(JG,ICOL)
        ENDIF
      ENDDO
    ENDDO
  ENDDO
  IF (YD%PROFILE) CALL YD%MARK(3,.FALSE.)
  IF (LHOOK) CALL DR_HOOK('GAS_BATCH%LOAD',1,ZHOOK_HANDLE)
END SUBROUTINE LOAD

SUBROUTINE RELEASE(YD)
  CLASS(GAS_BATCH_CONTEXT_TYPE), INTENT(INOUT) :: YD
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('GAS_BATCH%RELEASE',0,ZHOOK_HANDLE)
  IF (ALLOCATED(YD%OD_SW)) THEN
    !$ACC WAIT(1)
#ifdef _OPENACC
    CALL YD%SINGLE%DELETE_DEVICE()
    CALL YD%THERMO%DELETE_DEVICE()
    CALL YD%GAS%DELETE_DEVICE()
#endif
    !$ACC EXIT DATA DELETE(YD%OD_SW,YD%SSA_SW,YD%OD_LW,YD%PLANCK)
    !$ACC EXIT DATA DELETE(YD%ALB_DIRECT,YD%ALB_DIFFUSE,YD%ALB_LW,YD%EMISSION,YD%INCOMING)
    !$ACC EXIT DATA DELETE(YD)
    CALL YD%SINGLE%DEALLOCATE()
    CALL YD%THERMO%DEALLOCATE()
    CALL YD%GAS%DEALLOCATE()
    DEALLOCATE(YD%STAGED,YD%LAST,YD%OD_SW,YD%SSA_SW,YD%OD_LW,YD%PLANCK)
    DEALLOCATE(YD%ALB_DIRECT,YD%ALB_DIFFUSE,YD%ALB_LW,YD%EMISSION,YD%INCOMING)
  ENDIF
  YD%ACTIVE=0
  YD%CAPACITY=0
  IF (LHOOK) CALL DR_HOOK('GAS_BATCH%RELEASE',1,ZHOOK_HANDLE)
END SUBROUTINE RELEASE
END MODULE RADIATION_GAS_BATCH_CONTEXT_MOD
